// Сумнів — не привід натискати навздогад: запис лишається, питання
// потрапляє в moderation_notes і в ранкове зведення.
function Ask({ children }) {
  return (
    <>
      <h4>💬 Залишити коментар — коли сумніваєшся</h4>
      <ul>
        {children}
        <li>Будь-що, чого немає в цих правилах.</li>
      </ul>
      <p style={{ margin: '6px 0 0' }}>
        Запис лишається на місці, а коментар — відкритим, доки його не оброблять. Його видно на
        картці й щоранку в зведенні в адмін-чаті.
      </p>
    </>
  );
}

function Actives({ incomplete }) {
  return (
    <>
      {incomplete ? (
        <p className="lead">
          Ці записи вже на сайті, але без одного з пʼяти полів. Знайди поле в джерелі й
          дозаповни. Немає його в джерелі — не прибирай сам: такі записи знімає Марія.
        </p>
      ) : (
        <p className="lead">
          Спершу показано записи, яких ще ніхто не перевіряв. Критерії ті самі, що для кандидатів:
          актуальна, повна, конкретна, українською.
        </p>
      )}

      <h4 style={{ color: C.green }}>🔗 Посилання робоче</h4>
      <ul>
        <li>Сторінка відкривається, це та сама програма, дати на картці збігаються зі сторінкою.</li>
        <li>Ставить «перевірено» з сьогоднішньою датою, запис лишається на сайті.</li>
      </ul>

      <h4 style={{ color: C.red }}>🗑 Прибрати</h4>
      <ul>
        <li>Не проходить один із чотирьох критеріїв — не актуальна, не повна, не конкретна, не українською — або запис не для дітей (як у «Пропустити» на вкладці «Кандидати»).</li>
        <li>Запис зникає з сайту за кілька хвилин.</li>
      </ul>

      <h4>✏️ Редагувати</h4>
      <ul>
        <li>Поле хибне — виправ за правилами вкладки «Кандидати».</li>
        <li>«Зберегти чернеткою» тут лише зберігає правки: запис лишається на сайті.</li>
      </ul>

      <Ask />
    </>
  );
}

export default function ModerationRules({ tab }) {
  // На широкому екрані правила відкриті, на вузькому стоять над списком
  // згорнутими, щоб не штовхати картки вниз.
  const [open, setOpen] = useState(true);
  useEffect(() => {
    if (window.matchMedia('(max-width: 1099px)').matches) setOpen(false);
  }, []);

  return (
    <div className="mod-rules">
      <style dangerouslySetInnerHTML={{ __html: CSS }} />
      <details open={open} onToggle={(e) => setOpen(e.currentTarget.open)}>
        <summary>Правила модерації</summary>
        <p className="lead">
          Головне: на сайт іде лише те, що є на сторінці джерела. Чого там немає — не
          вигадуй: пропусти або залиш коментар.
        </p>
        {tab === 'drafts' ? <Drafts /> : <Actives incomplete={tab === 'incomplete'} />}
        <p className="note">
          Коментар разом із рішенням — це його причина, вона зберігається. Сірий рядок «Позначки
          конвеєра» — що помітили скрипти. Зміна на сайті — за кілька хвилин.
        </p>
      </details>
    </div>
  );
}
