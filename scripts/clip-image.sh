#!/bin/bash
# Готує скриншот із буфера обміну так, щоб асистент міг його ПОБАЧИТИ.
#
# Навіщо. Скриншоти з монітора йдуть на 3000-4000 пікселів завширшки, і API
# їх відхиляє: у переписці лишається «media removed». Людина бачить помилку
# на екрані, асистент — ні, і починається переказ словами.
#
# ocr-clipboard.sh поруч витягує з такого знімка ТЕКСТ. Цього досить для
# повідомлення про помилку, але не для інтерфейсу: де стоїть галочка, який
# пункт підсвічено, що сіре й неактивне — усе це втрачається. Тут інший шлях:
# зменшити картинку до прохідного розміру й лишити її картинкою.
#
# Використання:
#   ./scripts/clip-image.sh              — з буфера обміну
#   ./scripts/clip-image.sh знімок.png   — з файлу
#
# Друкує шлях до готового файлу. Далі асистент читає його як зображення.
#
# Працює на системних утилітах macOS, нічого не встановлює й нікуди не шле.
set -euo pipefail

# Ліміт API — 2000 пікселів по стороні. Беремо 1400 із запасом: дрібний текст
# інтерфейсу ще читається, а вага файлу падає на порядок.
#
# Межа не єдина: у довгій розмові з десятками картинок вичерпується загальний
# бюджет на зображення, і тоді не проходить навіть 900×480. Помилка при цьому
# каже про «2000 pixels» і збиває з пантелику. Якщо зменшений знімок теж не
# читається — справа не в розмірі, і лишається ocr-clipboard.sh поруч.
MAX_SIDE=1400

OUT_DIR="${TMPDIR:-/tmp}/dityam-clips"
mkdir -p "$OUT_DIR"
OUT="$OUT_DIR/clip-$(date +%H%M%S).png"

SRC="${1:-}"

if [ -z "$SRC" ]; then
  SRC="$(mktemp -t clip-src).png"
  osascript >/dev/null <<APPLESCRIPT || { echo "У буфері немає зображення. Зроби знімок (Cmd+Ctrl+Shift+4) і повтори." >&2; exit 1; }
set d to (the clipboard as «class PNGf»)
set f to open for access POSIX file "$SRC" with write permission
set eof f to 0
write d to f
close access f
APPLESCRIPT
fi

[ -f "$SRC" ] || { echo "Немає файлу: $SRC" >&2; exit 1; }

cp "$SRC" "$OUT"
# -Z зменшує ЛИШЕ якщо картинка більша за межу й зберігає пропорції.
sips -Z "$MAX_SIDE" "$OUT" >/dev/null 2>&1

read -r W H < <(sips -g pixelWidth -g pixelHeight "$OUT" 2>/dev/null \
  | awk '/pixelWidth/{w=$2} /pixelHeight/{h=$2} END{print w, h}')

echo "$OUT"
echo "розмір: ${W}x${H}, $(du -h "$OUT" | cut -f1)" >&2
