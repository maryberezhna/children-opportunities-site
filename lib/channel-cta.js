// Скільки закликів до каналу зараз видно на екрані.
//
// Привід (Марія, 28.09.2026, знімок головної з телефона): «3 рази на екрані
// "щоб не шукати вручну" — дуже жорстко». На одному екрані стояли картка в
// списку, спливна підказка й блок унизу сторінки — з тим самим заголовком і
// тим самим текстом.
//
// Правило просте: **підказка не зʼявляється, поки видно постійний блок**.
// Постійний блок нікуди не дінеться й людина його прочитає; підказка ж
// перекриває вміст і зникає сама. Коли обидва на екрані, поступається саме
// вона.
//
// Чому лічильник, а не прапорець: карток у списку кілька (одна на 20
// можливостей), і поки хоч одна в полі зору — підказки немає.
//
// Модуль без React навмисно: його читає і компонент картки
// (app/TelegramCard.js), і підказка (app/SubscribePopup.js), а спільний стан
// між двома гілками дерева інакше довелося б тягти через контекст.

let visible = 0;
const listeners = new Set();

const notify = () => { for (const fn of listeners) fn(visible > 0); };

/** Картка зʼявилась у полі зору. Повертає функцію «зникла». */
export function holdChannelCta() {
  visible += 1;
  if (visible === 1) notify();
  let released = false;
  return () => {
    if (released) return;
    released = true;
    visible = Math.max(0, visible - 1);
    if (visible === 0) notify();
  };
}

/** Чи видно зараз хоч один постійний заклик до каналу. */
export const channelCtaVisible = () => visible > 0;

/**
 * Підписка на зміни. Викликає fn(true|false) щоразу, коли стан міняється з
 * «жодної картки» на «є картка» і навпаки. Повертає функцію відписки.
 */
export function onChannelCtaVisibility(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
