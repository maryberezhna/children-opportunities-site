/**
 * Записи каталогу, що їдуть у браузер, — без порожніх полів.
 *
 * Головна віддає в HTML усі ~730 живих записів (список фільтрує й шукає в
 * браузері). 07.10.2026 Марія спитала «чи не перевантажені сторінки»: HTML
 * головної важив 1,27 МБ, із них 0,9 МБ — ці записи, і кожен п'ятий байт там
 * був порожнечею на кшталт `"featured_week":null` — у 727 записах із 731.
 * Телефон мусив її завантажити й розібрати, перш ніж сторінка оживе.
 *
 * Прибираємо null, false і порожні списки. Для коду списку це те саме:
 * поле читається як `o.x || …` чи `(o.x || [])`, а суворих порівнянь із null
 * у публічних компонентах немає (див. tests/client-rows.test.mjs). Нулі й
 * порожні рядки лишаються — це значення, а не відсутність.
 */
export function clientRows(rows = []) {
  return rows.map((row) => {
    const out = {};
    for (const key of Object.keys(row)) {
      const v = row[key];
      if (v === null || v === undefined || v === false) continue;
      if (Array.isArray(v) && v.length === 0) continue;
      out[key] = v;
    }
    return out;
  });
}
