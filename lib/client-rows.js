import { publicSource } from './source-link.js';

/**
 * Записи каталогу, що їдуть у браузер, — без порожніх полів.
 *
 * Головна віддає в HTML усі ~730 живих записів (список фільтрує й шукає в
 * браузері). 07.10.2026 Марія спитала «чи не перевантажені сторінки»: HTML
 * головної важив 1,27 МБ, із них 0,9 МБ — ці записи, і кожен п'ятий байт там
 * був порожнечею на кшталт `"featured_week":null` — у 727 записах із 731.
 * Телефон мусив її завантажити й розібрати, перш ніж сторінка оживе.
 *
 * Прибираємо null, false і порожні списки. Для коду списку це те саме:
 * поле читається як `o.x || …` чи `(o.x || [])`, а суворих порівнянь із null
 * у публічних компонентах немає (див. tests/client-rows.test.mjs). Нулі й
 * порожні рядки лишаються — це значення, а не відсутність.
 */
// Адреси джерела й подачі в браузер списку не їдуть (Марія, 11.10.2026:
// «треба захиститися від копіювання»). Файл /api/catalog віддавав одним
// запитом усі ~700 описів разом із посиланнями на першоджерела — уся наша
// робота з пошуку джерел за один запит. Картка списку адрес не показує;
// посилання на організатора лишається на сторінці можливості (/o/…) і в
// її розмітці для пошуковиків та AI — їх ця функція не торкається.
const HIDDEN = new Set(['source_url', 'apply_url', 'canonical_url']);

export function clientRows(rows = [], lang = 'uk') {
  return rows.map((row) => {
    const out = {};
    for (const key of Object.keys(row)) {
      if (HIDDEN.has(key)) continue;
      const v = row[key];
      if (v === null || v === undefined || v === false) continue;
      if (Array.isArray(v) && v.length === 0) continue;
      out[key] = v;
    }
    // Назва організатора замість адреси: картці потрібна лише вона, і лише
    // та, яку можна показати (чужий канал і переказувачі — без назви).
    if ('source' in row || 'source_url' in row) {
      const name = publicSource(row, lang).sourceName;
      if (name) out.source = name;
      else delete out.source;
    }
    return out;
  });
}
