/**
 * Довжина заголовка сторінки — одне число на весь сайт.
 *
 * Привід — Site Scan у Bing Webmaster Tools 05.10.2026: 678 сторінок, 0
 * помилок, 215 попереджень, із них 156 «Title too long». Пошук показує
 * близько 60 символів і далі обрізає; усе, що довше, людина в результатах не
 * побачить.
 *
 * Правило просте: назву програми ніколи не ріжемо (це власна назва запису), а
 * те, що дописали ми самі, — складаємо так, щоб уміщалось.
 */

/** Пошук показує близько 60 символів заголовка; далі обрізає трьома крапками. */
export const TITLE_MAX = 65;

/**
 * Перший варіант, що вміщається в TITLE_MAX. Якщо не вміщається жоден —
 * останній, тобто найкоротший із написаних.
 *
 * Варіанти йдуть від найповнішого до найкоротшого: так довгий хвіст із
 * ключовими словами лишається там, де на нього є місце, і зникає лише там,
 * де назва міста чи програми й так зайняла рядок.
 */
export function fitTitle(...variants) {
  const list = variants.map((v) => String(v || '').trim()).filter(Boolean);
  return list.find((v) => v.length <= TITLE_MAX) || list[list.length - 1] || '';
}
