//
// false — /plus, блоки Dityam+ на сторінках і кнопки «Хочу першим» ведуть у
// список очікування в @DityamPlusBot. true — туди ж, але вже до анкети й оплати.
//
// Відкрито 24.09.2026 за рішенням Марії (14.09.2026 було: «підготувати, старт
// скажу я»). Разом із цим запускається воркфлоу «Dityam+ — launch to waitlist»
// (.github/workflows/plus-launch.yml): список очікування має дізнатись першим
// і отримати обіцяне — промокод FIRST (перший місяць 1 грн замість 119, перший
// рік 799 замість 999).
//
// Чому відкрили саме тоді: прапорець стримував лише сайт. У боті перевірка
// стоїть на одному місці — на кліку з ?start=waitlist, — а будь-яке наступне
// просте /start вело у повний платний флоу. 24.09.2026 дві людини так і
// пройшли його, одна заплатила. Тобто продаж фактично вже йшов, просто сайт
// про це мовчав і люди зі списку очікування платили б повну ціну.
export const PLUS_SALES_OPEN = true;

export const PLUS_BOT = 'DityamPlusBot';

// start-параметр видно в аналітиці бота: звідки прийшла людина.
export const plusBotUrl = (start = 'site') => `https://t.me/${PLUS_BOT}?start=${start}`;

// Мітка джерела в діп-лінку: `from_<звідки>`.
//
// Навіщо окремий префікс. `promo_<код>_<звідки>` уже зайнятий і роздає знижку,
// а простий `?start=channel` бот проковтував мовчки — джерело нікуди не
// потрапляло. Пости в каналі 25.09.2026 вели на сторінку /plus, звідки людина
// мусила дійти до бота ще двома кліками, і звідки саме вона прийшла, ми не
// знали взагалі.
export const plusFromUrl = (where) => plusBotUrl(`from_${where}`);

/** `from_channel_new` → `channel_new`. Не мітка — null (токен, промокод, порожньо). */
export function parseSourceArg(startArg) {
  const m = String(startArg ?? '').match(/^from[_-]([a-z0-9_-]{2,40})$/i);
  return m ? m[1].toLowerCase() : null;
}

