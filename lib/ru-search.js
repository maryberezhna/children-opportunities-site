/**
 * Пошукові системи росії й білорусі на сайт не пускаємо
 * (Марія, 02.10.2026: «закрий сайт для пошуку з росії і білорусі»).
 *
 * Два шари, бо вони роблять різне:
 *   • robots.txt (app/robots.js) — саме за ним Яндекс ПРИБИРАЄ сторінки з
 *     індексу. Заборона в robots.txt — документований спосіб деіндексації,
 *     і без неї сайт лишався б у видачі, навіть якщо робота не пускати;
 *   • відмова на вході (middleware.js) — щоб правило працювало й тоді, коли
 *     robots.txt зігнорували. robots.txt сам лишається відкритим для всіх:
 *     інакше робот не прочитає заборону й не знатиме, що йому йти.
 *
 * Чого це НЕ робить: сайт не зникне з google.ru. Google не вміє «не показуй у
 * цій країні» — ні заголовком, ні в Search Console. Єдиний спосіб закрити
 * сайт від людей із рф і білорусі — відмовляти за країною IP, а це окреме
 * рішення: так само відрізає українців із окупованих територій, бо вони
 * виходять через російські мережі.
 *
 * Білорусь власного пошуковика не має — там той самий Яндекс і Google.
 */

/**
 * Для robots.txt. «Yandex» одним рядком покриває всіх їхніх роботів — так
 * описано в документації Яндекса: секція User-agent: Yandex діє на весь
 * сімейство (YandexBot, YandexImages, YandexVideo…).
 */
export const RU_SEARCH_AGENTS = [
  'Yandex',       // Яндекс — основний пошук рф і білорусі
  'Mail.RU_Bot',  // Mail.ru / Поиск Mail.ru
  'StackRambler', // Rambler
  'SputnikBot',   // Спутник (держпошуковик рф)
];

/**
 * Той самий перелік для перевірки живого запиту.
 *
 * Збігаємось лише з роботами, не з людьми: Яндекс-браузер підписується
 * «YaBrowser», а не «Yandex», і живу людину з таким браузером ми не чіпаємо.
 * Тому шукаємо або «Yandex<щось>/<версія>», або їхню адресу довідки про
 * роботів — обидві є в кожному їхньому краулері.
 */
const RU_SEARCH_BOT = new RegExp([
  'yandex[a-z]*/\\d',        // YandexBot/3.0, YandexImages/3.0
  'yandex\\.com/bots',       // +http://yandex.com/bots
  'mail\\.ru_bot',           // Mail.RU_Bot/2.0
  'go\\.mail\\.ru/help/robots',
  'stackrambler',
  'sputnikbot',
].join('|'), 'i');

/** Чи це пошуковий робот рф або білорусі. */
export function isRuSearchBot(ua) {
  return RU_SEARCH_BOT.test(String(ua || ''));
}
