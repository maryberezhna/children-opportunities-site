/**
 * Сторінки «місто × підбірка»: /kyiv/bezkoshtovni-hurtky.
 *
 * Навіщо. Тематичні сторінки закрили категорійні запити («безкоштовні гуртки
 * для дітей»), але локальний хвіст — «безкоштовні гуртки Київ», «гуртки для
 * дітей Житомир» — досі веде на головну або нікуди. Це найчастіший формат
 * запиту батьків і водночас найдешевший трафік: конкуренція на перетині
 * «тема × місто» майже нульова.
 *
 * Проти тонкого контенту працює поріг: сторінка існує, лише коли в місті є
 * MIN_LOCAL записів САМЕ цього міста (без «Вся Україна»). Інакше сторінки
 * різних міст відрізнялись би тільки заголовком — за таке Google понижує весь
 * сайт, а не одну сторінку. Комбінації нижче порогу віддають 404 і не
 * потрапляють у sitemap; щойно гео-розмітка доростає — сторінка зʼявляється
 * сама, без правок коду.
 */
export const MIN_LOCAL = 5;

/** Запис привʼязаний саме до цього міста. */
export const isLocal = (o, cityUa) => (o.cities || []).includes(cityUa);

/**
 * Що показує сторінка: локальні записи плюс всеукраїнські — так само, як
 * сторінка міста. Батькам у Житомирі всеукраїнський онлайн-гурток доступний
 * так само, як місцевий; ховати його означало б відповідати на запит гірше,
 * ніж уміємо.
 */
export const inCityOrNationwide = (o, cityUa) =>
  isLocal(o, cityUa) || (o.cities || []).includes('Вся Україна');

export const cityTopicRows = (rows, topic, cityUa) =>
  rows.filter(topic.match).filter((o) => inCityOrNationwide(o, cityUa));

export const localTopicCount = (rows, topic, cityUa) =>
  rows.filter(topic.match).filter((o) => isLocal(o, cityUa)).length;

/** Комбінації, що мають право на сторінку — для sitemap і статичних параметрів. */
export function qualifyingCombos(rows) {
  const out = [];
  for (const [citySlug, meta] of Object.entries(CITY_META)) {
    for (const topic of TOPIC_LIST) {
      if (localTopicCount(rows, topic, meta.ua) >= MIN_LOCAL) {
        out.push({ citySlug, topicSlug: topic.slug });
      }
    }
  }
  return out;
}

