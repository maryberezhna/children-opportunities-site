/**
 * Запис зі списку олімпіад МОН — за назвою, а не за типом.
 *
 * Тип сюди не годиться: `olympiad` носять і міжнародні олімпіади (IOAA, IMO), і
 * олімпіада МАН з філософії, і UOAI зі штучного інтелекту. Ця сторінка саме
 * про шкільний цикл МОН, тож збіг рахуємо по назві «Всеукраїнська олімпіада».
 */
export const isMonOlympiad = (o) =>
  o?.opportunity_type === 'olympiad'
  // \b тут не працює: у JavaScript межа слова визначена лише для латиниці
  // ([A-Za-z0-9_]), тож після кириличного «олімпіада» її не існує й умова не
  // збігалася НІКОЛИ. Путівник стояв із порожнім списком від запуску
  // 27.09.2026 до 28.09.2026, хоча в базі було 26 придатних записів.
  && /^Всеукраїнська олімпіада\s/i.test(o?.title || '');

