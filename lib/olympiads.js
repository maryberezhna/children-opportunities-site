const SUBJECT_RES = Object.entries(SUBJECT_KEYS)
  .map(([name, { stem }]) => [name, new RegExp(`(?:^|[^\\p{L}])${stem}`, 'iu')]);

/** Короткий підпис предмета для чипа: «Англійська мова» → «Англійська». */
export const subjectChip = (name) => SUBJECT_KEYS[name]?.chip || name;

/**
 * Предмет наказу, про який картка, — або null.
 *
 * null, коли запис не олімпіада МОН, коли це олімпіада для початкової школи
 * (у наказі класи 8–11, це інше змагання) і коли назва підходить під два
 * предмети одразу: вгадане посилання гірше за відсутнє.
 */
export function subjectOf(o) {
  if (!isMonOlympiad(o)) return null;
  const rest = o.title.replace(/^Всеукраїнська олімпіада\s+/i, '');
  if (/початков/i.test(rest)) return null;
  const hits = SUBJECT_RES.filter(([, re]) => re.test(rest));
  return hits.length === 1 ? hits[0][0] : null;
}

/**
 * Назва предмета → slug його живої картки, у порядку таблиці (SUBJECTS).
 *
 * `items` — те, що сторінка вже показує списком: живі олімпіади МОН. Немає
 * картки — немає й ключа, і сторінка лишає назву текстом. Дві картки на один
 * предмет — береться перша в порядку `items`.
 */
export function subjectCards(items) {
  const found = new Map();
  for (const o of items || []) {
    const name = subjectOf(o);
    if (name && o.slug && !found.has(name)) found.set(name, o.slug);
  }
  return new Map(SUBJECTS.filter((s) => found.has(s.name)).map((s) => [s.name, found.get(s.name)]));
}
