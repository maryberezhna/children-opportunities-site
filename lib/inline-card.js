// Позиція вбудованої картки у списку (Telegram-картка між картками можливостей).
//
// Повертає індекс картки, ПІСЛЯ якої вставити блок, або -1, якщо список
// закороткий. У короткому списку (менше `min` карток) блок не ставимо взагалі:
// два-три записи й одразу реклама каналу читаються як порожня сторінка.
// Якщо карток менше за `after`, блок стає в кінець — його все одно побачать.
export function inlineCardAfter(count, { after = 6, min = 3 } = {}) {
  if (!Number.isInteger(count) || count < min) return -1;
  return Math.min(after, count) - 1;
}
