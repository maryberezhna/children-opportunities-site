// Де в списку можливостей стоїть картка каналу.
//
// До 28.09.2026 картка була ОДНА і стояла після четвертої можливості. На
// головній видно було шість карток, а одразу під списком ішов блок «Щоб не
// шукати вручну» з тими самими словами — тож той самий заклик траплявся двічі
// за пів екрана (Марія: «майже 2 рази, дуже близько»).
//
// Тепер картка повторюється рівномірно — раз на `every` можливостей. Це
// свідомий обмін: людина, яка гортає довго, бачить заклик кілька разів, але
// між ними двадцять карток, а не чотири.

/**
 * Індекси карток, ПІСЛЯ яких вставити блок.
 *
 * Повертає Set, бо його єдине призначення — перевірка `has(i)` у циклі
 * рендера. Порожній Set означає «не вставляти»: у списку з кількох записів
 * заклик до каналу читається як порожня сторінка.
 *
 * `min` — скільки карток має бути, щоб блок узагалі зʼявився. Перший блок
 * стає після `every`-ї картки, а не в кінці короткого списку: у кінці його
 * і так підпирає блок унизу сторінки.
 */
export function inlineCardPositions(count, { every = 20 } = {}) {
  const out = new Set();
  if (!Number.isInteger(count) || !Number.isInteger(every) || every < 1) return out;
  // Останню позицію пропускаємо: блок одразу під останньою карткою зливається
  // з тим, що йде під списком, — і на телефоні 28.09.2026 саме так і вийшло:
  // картка стала над кнопкою «Показати ще», а за нею одразу той самий блок
  // унизу сторінки й спливна підказка. Три однакові заклики на екран.
  //
  // Запасного правила «якщо список короткий — показати хоч раз у кінці» тут
  // теж немає, і з тієї ж причини: у короткому списку заклик і так є під
  // ним. Немає двадцяти карток — немає вбудованої картки.
  for (let i = every; i < count; i += every) out.add(i - 1);
  return out;
}

/**
 * Стара однопозиційна форма. Лишається для місць, де картка справді одна.
 * @deprecated на користь inlineCardPositions
 */
export function inlineCardAfter(count, { after = 6, min = 3 } = {}) {
  if (!Number.isInteger(count) || count < min) return -1;
  return Math.min(after, count) - 1;
}
