/**
 * Стан статті на дату: closed — минув deadline (подача за цими правилами
 * завершилась), stale — минув reviewBy (час переперевірити). Дати — YYYY-MM-DD
 * за Києвом: «до 1 листопада» означає, що 1 листопада ще можна.
 */
export function postState(post, today = new Date()) {
  const day = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Kyiv' }).format(today);
  return {
    closed: Boolean(post?.deadline) && day > post.deadline,
    stale: Boolean(post?.reviewBy) && day > post.reviewBy,
  };
}

export const postBySlug = (slug) => BLOG_POSTS.find((p) => p.slug === slug) || null;

/**
 * Статті для блоку «Статті на цю тему» на сторінці підбірки (22.10.2026, Марія:
 * блог — «те, що прямо потрібно, щоб підвищити SEO і GEO»). Підбірка має
 * органіку, тож посилання з неї передає вагу статті, а стаття — назад підбірці.
 * Спершу статті з живим списком саме цієї підбірки (cards.topic), далі ті, де
 * вона серед related; найновіші першими.
 */
export function postsForTopic(slug, limit = 4) {
  const byDate = (a, b) => (a.published < b.published ? 1 : a.published > b.published ? -1 : 0);
  const own = BLOG_POSTS.filter((p) => p.cards?.topic === slug).sort(byDate);
  const near = BLOG_POSTS.filter((p) => p.cards?.topic !== slug && p.related?.includes(slug)).sort(byDate);
  return [...own, ...near].slice(0, limit);
}

/** Записи для головної блогу: спершу статті (новіші вище), далі путівники. */
export function blogEntries() {
  const posts = [...BLOG_POSTS]
    .sort((a, b) => (a.published < b.published ? 1 : -1))
    .map((p) => ({ href: blogPath(p.slug), title: p.title, description: p.description, hero: p.hero, date: p.checked }));
  return [...posts, ...BLOG_GUIDES.map((g) => ({ ...g, date: null }))];
}

/**
 * Розбиває текст із розміткою [текст](адреса) на частини для рендеру.
 * Повертає [{ text } | { text, href, internal }].
 */
export function richParts(text) {
  const out = [];
  const re = /\[([^\]]+)\]\(([^)\s]+)\)/g;
  let last = 0;
  let m;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push({ text: text.slice(last, m.index) });
    out.push({ text: m[1], href: m[2], internal: m[2].startsWith('/') });
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push({ text: text.slice(last) });
  return out;
}

/** Усі внутрішні посилання статті — для тесту перелінковки. */
export function internalLinks(post) {
  const texts = [
    post.intro,
    ...post.sections.flatMap((s) => [s.lead, ...(s.paras || []), ...(s.list || []), ...(s.after || []),
      ...(s.steps || []).map((x) => x.d)]),
  ].filter(Boolean);
  return texts.flatMap((t) => richParts(t).filter((p) => p.internal).map((p) => p.href));
}
