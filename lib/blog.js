/** Записи для головної блогу: спершу статті (новіші вище), далі путівники. */
export function blogEntries() {
  const posts = [...BLOG_POSTS]
    .sort((a, b) => (a.published < b.published ? 1 : -1))
    .map((p) => ({ href: blogPath(p.slug), title: p.title, description: p.description, hero: p.hero, date: p.checked }));
  return [...posts, ...BLOG_GUIDES.map((g) => ({ ...g, date: null }))];
}

/**
 * Розбиває текст із розміткою [текст](адреса) на частини для рендеру.
 * Повертає [{ text } | { text, href, internal }].
 */
export function richParts(text) {
  const out = [];
  const re = /\[([^\]]+)\]\(([^)\s]+)\)/g;
  let last = 0;
  let m;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push({ text: text.slice(last, m.index) });
    out.push({ text: m[1], href: m[2], internal: m[2].startsWith('/') });
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push({ text: text.slice(last) });
  return out;
}

/** Усі внутрішні посилання статті — для тесту перелінковки. */
export function internalLinks(post) {
  const texts = [
    post.intro,
    ...post.sections.flatMap((s) => [s.lead, ...(s.paras || []), ...(s.list || []), ...(s.after || []),
      ...(s.steps || []).map((x) => x.d)]),
  ].filter(Boolean);
  return texts.flatMap((t) => richParts(t).filter((p) => p.internal).map((p) => p.href));
}
