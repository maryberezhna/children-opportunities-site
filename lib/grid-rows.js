/**
 * Блок на весь рядок сітки не має лишати по собі порожньої клітинки.
 *
 * У стрічці головної олімпіади МОН стоять однією карткою на всю ширину
 * (grid-column: 1 / -1), і Telegram-картка теж. Коли такий блок припадав на
 * непарне місце в двоколонковій сітці, попередня картка лишалась сама в
 * рядку, а поруч зяяла дірка (Марія, 30.09.2026: «чому тут пусто, немає
 * картки — так ніколи не має бути»).
 *
 * Тут блок переставляється ПЕРЕД неповним рядком: рядки завжди повні, а
 * порядок у DOM збігається з тим, що на екрані (клавіатура й читач екрана
 * йдуть так само, як око). Зсув — на одну картку, і лише перед блоком.
 * Для сіток з іншою кількістю колонок (auto-fill на сторінках міст)
 * лишок закриває grid-auto-flow: dense у .v2-grid.
 *
 * @param {T[]} cells — клітинки в порядку появи
 * @param {(cell: T) => boolean} isFull — чи займає клітинка весь рядок
 * @param {number} cols — колонок у сітці
 * @returns {T[]}
 * @template T
 */
export function packFullRows(cells, isFull, cols = 2) {
  const out = [];
  let inRow = 0;
  for (const cell of cells) {
    if (isFull(cell)) {
      // Неповний рядок перед блоком: блок стає перед ним, рядок лишається
      // відкритим і добере наступні картки.
      if (inRow > 0) out.splice(out.length - inRow, 0, cell);
      else out.push(cell);
      continue;
    }
    out.push(cell);
    inRow = (inRow + 1) % cols;
  }
  return out;
}

/**
 * Скільки записів показати, щоб перед «Показати ще» останній рядок був повний.
 *
 * Марія, 07.10.2026: «чому тут пусто» — під останньою карткою порожня
 * клітинка, а нижче кнопка «Показати ще». Ліміт рахує записи, а блок на весь
 * рядок (група олімпіад) теж запис: із 6 записів карток виходило 5, і шоста
 * клітинка зяяла, хоча карток у запасі було досить.
 *
 * Тут ліміт добирає наступні записи, доки звичайних карток не стане кратно
 * колонкам. Кінець списку не чіпаємо: якщо показати більше нічого, неповний
 * останній рядок — це просто кінець.
 *
 * @param {T[]} entries — усі записи в порядку показу
 * @param {number} limit — скільки показати за поточним «Показати ще»
 * @param {(entry: T) => boolean} isFull — чи займає запис весь рядок
 * @param {number} cols — колонок у сітці зараз
 * @returns {number} скільки записів показати
 * @template T
 */
export function fillLastRow(entries, limit, isFull, cols = 2) {
  let end = Math.min(limit, entries.length);
  if (cols <= 1 || end >= entries.length) return end;
  let cards = 0;
  for (let i = 0; i < end; i += 1) if (!isFull(entries[i])) cards += 1;
  while (cards % cols !== 0 && end < entries.length) {
    if (!isFull(entries[end])) cards += 1;
    end += 1;
  }
  return end;
}
