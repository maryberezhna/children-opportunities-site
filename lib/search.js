// Пошук по каталогу. Раніше запит шукався як суцільний підрядок у склеєних
// полях — і «build for future» не знаходив «Build Future» (зайве «for»
// ламало збіг), «шахи київ» не знаходив шахи в Києві (слова в різних полях),
// а «табори» не бачив «табір» (українська морфологія). Тут запит ділиться
// на слова: кожне значуще слово має знайтися десь у записі — як підрядок
// або за основою слова з урахуванням чергування і/о та ї/є.
//
// Свідомо НЕ Postgres full-text: пошук працює по вже завантажених рядках у
// браузері (фільтри й лічильник потребують повного набору так і так), а
// вбудованого українського словника в tsvector немає.

// Службові слова не мають блокувати збіг: «build for future» → build, future.
const STOP = new Set([
  'і', 'й', 'та', 'або', 'чи', 'для', 'в', 'у', 'на', 'з', 'зі', 'із',
  'до', 'по', 'про', 'від', 'без', 'під', 'при', 'як',
  'a', 'an', 'and', 'or', 'for', 'the', 'of', 'in', 'on', 'at', 'to', 'by',
]);

// Апострофи в даних живуть у трьох варіантах (ʼ ' ’) — зводимо до одного,
// інакше «комп'ютер» із клавіатури не збігається з «компʼютером» зі скрапера.
export const normalize = (s) => String(s || '')
  .toLowerCase()
  .replace(/[ʼ’‘`]/g, "'");

// Обрізання типових закінчень — двічі, бо «гуртками» знімає «ами» лише за
// другим заходом після «и». Основа коротша за 4 літери лишається як є:
// різати «шахи» до «ш» означало б збіг з чим завгодно.
const ENDINGS = /(ями|ами|ові|еві|ах|ях|ам|ям|ів|їв|ей|ою|ею|єю|ий|ій|ії|а|я|о|е|у|ю|и|і|ї|ь)$/;
export const stem = (w) => {
  let s = w;
  for (let i = 0; i < 2; i += 1) {
    if (s.length < 5) break;
    const next = s.replace(ENDINGS, '');
    if (next === s) break;
    s = next;
  }
  return s;
};

// Чергування голосних в останньому закритому складі: табір→табору (і/о),
// Київ→Києва (ї/є). Без цього стеми «табір» і «табор» не збігаються ніяк.
const ALT = { 'і': ['о', 'е'], 'ї': ['є'] };
export const stemVariants = (s) => {
  const out = new Set([s]);
  const m = /[ії](?=[^аеиоуюяєії]*$)/.exec(s);
  if (m) {
    for (const alt of ALT[s[m.index]] || []) {
      out.add(s.slice(0, m.index) + alt + s.slice(m.index + 1));
    }
  }
  // Випадна голосна: гурток→гуртки, садок→садки. Основа «гурток» отримує
  // варіант «гуртк», який і дає збіг зі стемом множини.
  const f = /([^аеиоуюяєіїь])[ое]([^аеиоуюяєіїь])$/.exec(s);
  if (f) out.add(s.slice(0, f.index) + f[1] + f[2]);
  return out;
};

/** Слова запиту, які мають знайтися. Порожній масив = показувати все. */
export const queryTokens = (q) => normalize(q)
  .split(/[^a-zа-яіїєґ0-9']+/i)
  .filter((w) => w.length > 1 && !STOP.has(w));

/**
 * Індекс одного запису: суцільний текст для підрядкових збігів (числа,
 * абревіатури, частини слів) і стеми слів для морфологічних.
 * Рахується один раз на запис, а не на кожне натискання клавіші.
 */
export function buildHaystack(fields) {
  const text = fields.filter(Boolean).map(normalize).join(' ');
  // Слова коротші за 3 літери в стеми не йдуть: «та», «до», «як» збігалися б
  // префіксом із половиною запитів. Підрядковий пошук по text їх усе одно бачить.
  const words = [...new Set(text.split(/[^a-zа-яіїєґ0-9']+/i).filter((w) => w.length > 2))];
  const stems = words.flatMap((w) => [...stemVariants(stem(w))]);
  return { text, stems };
}

// Префіксний збіг лише від 4 літер: «табор» ⊃ «та» знаходив би табори в
// кожному записі зі сполучником «та». Коротші основи мають збігтися точно.
const prefixOk = (a, b) =>
  a === b
  || (b.length >= 4 && a.startsWith(b))
  || (a.length >= 4 && b.startsWith(a));

const tokenMatches = (token, hay) => {
  if (hay.text.includes(token)) return true;
  const tv = [...stemVariants(stem(token))];
  // Обидва напрямки: «гуртки» (стем «гуртк») має знаходити «гурток», а
  // «гурток» — записи зі словом «гуртки».
  return hay.stems.some((s) => tv.some((t) => prefixOk(s, t)));
};

/** Чи відповідає запис запиту: кожне значуще слово знайшлося хоч десь. */
export const matchesQuery = (tokens, hay) => tokens.every((t) => tokenMatches(t, hay));
