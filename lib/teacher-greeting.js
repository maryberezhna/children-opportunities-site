// По батькові. Російського «-овна» («Елена Петровна») навмисно немає.
// Чоловічі -ович/-евич бувають і прізвищами (Мартинович) — тоді рятує
// перевірка статі імені.
const PATRONYMIC_F = /(івна|ївна)$/;
const PATRONYMIC_M = /(ович|евич|йович|ьович)$|^(ілліч|кузьмич|лукич|савич|фомич)$/;

// Слово імені: лише кирилиця, апостроф і дефіс між частинами.
const WORD = /^[а-щьюяґєії']+(-[а-щьюяґєії']+)*$/;

const lower = (w) => w.toLocaleLowerCase('uk-UA');
const genderOfPatronymic = (w) => (PATRONYMIC_F.test(w) ? 'feminine' : PATRONYMIC_M.test(w) ? 'masculine' : null);
const titleCase = (w) => w.split('-').map((p) => p.charAt(0).toLocaleUpperCase('uk-UA') + p.slice(1)).join('-');

// Імʼя в кличному відмінку зі словника: { gender, vocative } або null.
// Подвійне — якщо кожна частина є в словнику однієї статі.
function givenVocative(w) {
  const parts = w.split('-');
  for (const [gender, dict] of [['feminine', FEMALE], ['masculine', MALE]]) {
    if (parts.every((p) => Object.hasOwn(dict, p))) return { gender, vocative: parts.map((p) => dict[p]).join('-') };
  }
  return null;
}

// По батькові в кличному: Петрівна → Петрівно, Миколайович → Миколайовичу.
const patronymicVocative = (w) => titleCase(PATRONYMIC_F.test(w) ? `${w.slice(0, -1)}о` : `${w}у`).replace(/'/g, 'ʼ');

/**
 * Звертання в кличному відмінку — «Олено Петрівно» чи «Ігорю» — або null,
 * якщо певності немає.
 */
export function teacherVocative(raw) {
  const words = String(raw || '')
    .replace(/[’ʼ`´‘]/g, "'")
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map(lower);
  if (!words.length || words.length > 4) return null;
  if (!words.every((w) => WORD.test(w))) return null;

  const p = words.findIndex((w) => genderOfPatronymic(w));
  if (p >= 0) {
    // Імʼя — перед по батькові. По батькові першим словом — не розуміємо.
    if (p === 0) return null;
    const given = givenVocative(words[p - 1]);
    if (!given || given.gender !== genderOfPatronymic(words[p])) return null;
    return `${given.vocative} ${patronymicVocative(words[p])}`;
  }

  // По батькові немає: імʼя — перше або друге слово, лише зі словника.
  for (const w of words.slice(0, 2)) {
    const given = givenVocative(w);
    if (given) return given.vocative;
  }
  return null;
}

/** «Олено Петрівно, добрий день!» або, якщо не певні, «Добрий день!». */
export function teacherGreeting(raw) {
  const v = teacherVocative(raw);
  return v ? `${v}, добрий день!` : GREETING_FALLBACK;
}
