/**
 * «Зараз нічна тема — лишити чи перейти на світлу?»
 *
 * Марія, 04.10.2026: «покажи на сайті попап у нічний час, що зараз активована
 * темна тема, чи бажаєте залишити, чи перейти на світлу. Час для України».
 *
 * Навіщо взагалі питати. Нічна тема вмикається сама за налаштуванням системи,
 * і людина може не зрозуміти, чому сайт раптом темний: вирішить, що зламалось.
 * Питаємо один раз і більше ніколи — попап, який повертається, це не турбота.
 *
 * Час рахуємо КИЇВСЬКИЙ, а не браузерний: «ніч» тут про те, коли людина
 * дивиться сайт з України, і мама у Варшаві чи Торонто не має бачити «зараз
 * ніч» о своїй шостій вечора.
 */

/** Нічні години за Києвом: з 21:00 до 07:00. */
export const NIGHT_FROM = 21;
export const NIGHT_TO = 7;

/**
 * Котра зараз година в Києві. Через Intl, а не через зсув у годинах: Україна
 * переходить на літній час, і зашите «+2» помилялося б пів року.
 */
export function kyivHour(now = new Date()) {
  const h = new Intl.DateTimeFormat('uk-UA', {
    timeZone: 'Europe/Kyiv', hour: '2-digit', hour12: false,
  }).format(now);
  return Number(h);
}

/** Чи зараз ніч за Києвом. */
export function isKyivNight(now = new Date()) {
  const h = kyivHour(now);
  return h >= NIGHT_FROM || h < NIGHT_TO;
}

/**
 * Чи показувати попап.
 *
 * Усі умови разом:
 *   • зараз ніч за Києвом;
 *   • сайт справді темний цієї миті;
 *   • людина ще не обирала тему руками — у неї вже є відповідь, і перепитувати
 *     означало б не вірити власному інтерфейсу;
 *   • ми ще не питали на цьому пристрої.
 */
export function shouldAskAboutNight({ theme, systemDark, asked, now = new Date() } = {}) {
  if (asked) return false;
  if (theme === 'dark' || theme === 'light') return false;
  if (!systemDark) return false;
  return isKyivNight(now);
}

