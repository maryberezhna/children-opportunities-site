// Хто завис на шляху до оплати і що йому написати.
//
// Привід (Марія, 28.09.2026): «треба автоматично через 5 хв, якщо людина
// зависла до чи на етапі оплати».
//
// До цього не було нічого. Людина зупинялась — і ніхто ніколи не озивався:
// ні бот, ні зведення. @ttanyaost стояла на кроці з телефоном із 24.09,
// @Olka666 з 26.09, і обидві заблокували бота раніше, ніж хтось помітив.
// Мовчання після зупинки й перетворило бота на джерело роздратування.
//
// Модуль чистий — жодних запитів у базу й жодного HTTP, щоб правило «кому й
// що» перевірялось тестами, а не живими людьми.

/** Скільки хвилин без руху означає «зависла». */
export const STALL_MINUTES = 5;

/**
 * Де саме людина стоїть — або null, якщо писати нема про що.
 *
 * Стани по порядку шляху:
 *   'consent' — натиснула /start, але не дала згоди;
 *   'form'    — посеред анкети (flow_step виставлений);
 *   'phone'   — на кроці з номером;
 *   'pay'     — анкета заповнена, лишилась оплата.
 *
 * Активних підписників не чіпаємо ніколи: вони вже заплатили, і «ви
 * зупинились» для них — беззмістовне.
 */
export function stallStage(sub, { hasChild = false } = {}) {
  if (!sub || sub.status === 'active') return null;
  if (!sub.consent_at) return 'consent';
  if (sub.flow_step === 'phone') return 'phone';
  if (sub.flow_step) return 'form';
  if (!hasChild) return 'form';
  return 'pay';
}

/**
 * Чи час писати.
 *
 * Три умови разом: людина стоїть на якомусь кроці, від останньої її дії
 * минуло щонайменше STALL_MINUTES, і ми їй ще не писали. Позначку
 * stuck_notice_at ставить сам відправник — і тільки після того, як Telegram
 * прийняв повідомлення.
 */
export function shouldNudge(sub, { hasChild = false, now = new Date() } = {}) {
  if (sub?.stuck_notice_at) return false;
  const stage = stallStage(sub, { hasChild });
  if (!stage) return false;
  const last = Date.parse(sub.updated_at || sub.created_at || '');
  if (!last) return false;
  return now.getTime() - last >= STALL_MINUTES * 60 * 1000;
}

/**
 * Скільки годин без нагадування означає «нагадувач не працює».
 *
 * Правило — тут, а не в зведенні, бо воно про той самий механізм. Межа взята з
 * запасом у десятки разів від STALL_MINUTES: cron ходить щопʼять хвилин, тож
 * людина, яка стоїть другу годину без жодного слова від нас, означає не
 * невдалий збіг, а те, що нагадувач не ходить узагалі.
 *
 * Навіщо (02.10.2026). Маршрут /api/cron/nudge-stuck розкладений у vercel.json
 * на кожні пʼять хвилин. На тарифі Hobby Vercel такої частоти не дає, і тоді
 * вся турбота про тих, хто завис, просто не відбувається — мовчки, бо нічого
 * не падає. Той самий спосіб ламатись, що й у перевірок з цитатами: правило є,
 * ніхто його не кличе.
 */
export const NUDGE_SILENT_HOURS = 2;

/** Чи цей рядок — доказ, що нагадувач не ходить. */
export function provesNudgerSilent(sub, now = new Date()) {
  if (!sub || sub.stuck_notice_at) return false;
  // Заплатив або відписався — нагадувати нема про що, і тиша тут законна.
  if (sub.status === 'active' || sub.status === 'unsubscribed') return false;
  const last = Date.parse(sub.updated_at || sub.created_at || '');
  if (!last) return false;
  return now.getTime() - last >= NUDGE_SILENT_HOURS * 3600 * 1000;
}

// Тексти. Коротко й про одну дію: людина вже в боті, пояснювати продукт
// заново не треба. Без обіцянок на майбутнє й без «ви єдина, хто дійшов».
const TEXT = {
  consent:
    'Ви зупинились на першому кроці — згоді на обробку даних. Без неї не можемо '
    + 'питати про дитину. Якщо передумали, просто не відповідайте; якщо ні — '
    + 'кнопка «Погоджуюсь» вище.',
  form:
    'Ви зупинились на анкеті. Відповіді збереглись — щоб продовжити з того самого '
    + 'місця, напишіть /start.',
  phone:
    'Ви зупинились на кроці з номером телефону. Його можна пропустити — введете '
    + 'на сторінці оплати. Щоб продовжити, напишіть /start.',
  pay:
    'Анкета готова, лишився один крок — оплата. Щоб повернутись до неї, напишіть '
    + '/start. Якщо щось не спрацювало, напишіть сюди — розберемось.',
};

/** Текст під місце, де людина стала. Завжди закінчується запрошенням сказати. */
export function nudgeText(stage) {
  const body = TEXT[stage];
  if (!body) return null;
  return `${body}\n\nА якщо передумали — напишіть, будь ласка, кількома словами чому. Мені це справді важливо.`;
}
