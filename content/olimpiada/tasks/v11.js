// Середнє · терези: 2 квадрати = 1 квадрат + 2 кружечки → 1 квадрат = 2 кружечки.
import { svg, balance, shape, C } from '../art.js';

// Усі фігури одного розміру і стоять на одній лінії дна шальки, щоб було видно,
// що квадрати однакові між собою, а кружечки — між собою.
const SQ = 14; // «радіус» квадрата: сторона = 1.8 * 14 = 25.2
const CR = 12; // радіус кружечка (діаметр 24 — майже як сторона квадрата)
const square = (cx, cy) => shape('square', cx, cy, SQ, C.blue);
const dot = (cx, cy) => shape('circle', cx, cy, CR, C.red);

// Ліва шалька — 2 квадрати поруч; права — 1 квадрат і 2 кружечки.
// Між фігурами проміжок 8–9 px, щоб кружечки не зливались в один.
const art = svg(
  360,
  200,
  balance(
    360,
    (cx, cy) => `${square(cx - 17, cy + 1)}${square(cx + 17, cy + 1)}`,
    (cx, cy) => `${square(cx - 33, cy + 1)}${dot(cx + 1, cy + 2)}${dot(cx + 33, cy + 2)}`,
  ),
);

export const task = {
  id: 'v11',
  tier: 2,
  q: 'Терези в рівновазі. Усі квадрати однакові, усі кружечки теж. Скільки кружечків важать стільки ж, скільки 1 квадрат?',
  art,
  options: ['1', '2', '3', '4'],
};
