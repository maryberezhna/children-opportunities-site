// Легке · терези: 1 яблуко = 2 груші, скільки груш важать стільки ж, скільки 3 яблука.
import { svg, balance, apple, pear } from '../art.js';

// Ліва шалька — 1 яблуко в центрі; права — 2 груші поруч.
// Груші r=12 на ±18: між ними видимий проміжок, хвостики не чіпають ниток
// шальки, а низ (cy + 1.3r) лягає точно на дугу шальки.
const art = svg(
  360,
  200,
  balance(
    360,
    (cx, cy) => apple(cx, cy),
    (cx, cy) => `${pear(cx - 18, cy, 12)}${pear(cx + 18, cy, 12)}`,
  ),
);

export const task = {
  id: 'v04',
  tier: 1,
  q: 'Терези в рівновазі: 1 яблуко важить стільки ж, скільки 2 груші. Скільки груш важать стільки ж, скільки 3 яблука?',
  art,
  options: ['3', '5', '6', '9'],
};
