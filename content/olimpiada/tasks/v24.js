// Складне · картки з цифрами 2, 5 і 7: скільки різних тризначних чисел,
// якщо кожну картку взяти рівно 1 раз. Перестановок 3 карток — 3! = 6:
// 257, 275, 527, 572, 725, 752. Типові пастки — «3» (по 1 на картку)
// і «27» (3 × 3 × 3, ніби картки можна повторювати).
import { svg, rect, text, C } from '../art.js';

const CY = 100; // центри всіх карток на одній висоті
const STEP = 110; // відстань між центрами — щоб повернуті картки не торкались
const W = 70;
const H = 96;

// Картка з цифрою, трохи повернута навколо свого центра.
// Поворот робимо групою <g transform> — в art.js такого примітива немає.
const card = (cx, digit, rot) =>
  `<g transform="rotate(${rot} ${cx} ${CY})">${rect(cx - W / 2, CY - H / 2, W, H, C.white, 10)}${text(cx, CY + 16, digit, 44)}</g>`;

const CARDS = [
  ['2', -6],
  ['5', 0],
  ['7', 6],
];

const art = svg(360, 200, CARDS.map(([digit, rot], i) => card(70 + i * STEP, digit, rot)).join(''));

export const task = {
  id: 'v24',
  tier: 3,
  q: 'Є 3 картки з цифрами 2, 5 і 7. Скільки різних тризначних чисел можна скласти, якщо кожну картку використати рівно 1 раз?',
  art,
  options: ['3', '6', '9', '27'],
};
