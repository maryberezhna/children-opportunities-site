// Складне · рукостискання: 4 друзі, кожен тисне руку кожному по 1 разу.
// Пар із 4 людей — 6: 1–2, 1–3, 1–4, 2–3, 2–4, 3–4. Типова пастка — «4 × 3 = 12»
// (кожне рукостискання пораховане двічі) або «4» (по одному на людину).
import { svg, smiley, C } from '../art.js';

const CY = 70; // усі обличчя на одній горизонталі
const R = 36;
const STEP = 80; // відстань між центрами — щоб між обличчями був просвіт

// 4 обличчя в ряд різних кольорів, без ліній між ними:
// лінії підказали б відповідь, а дитина має порахувати пари сама.
const FACES = [C.yellow, C.pink, C.sky, C.green];

const art = svg(360, 140, FACES.map((fill, i) => smiley(60 + i * STEP, CY, R, fill)).join(''));

export const task = {
  id: 'v21',
  tier: 3,
  q: 'Зустрілися 4 друзі, і кожен потиснув руку кожному по 1 разу. Скільки всього було рукостискань?',
  art,
  options: ['4', '6', '8', '12'],
};
