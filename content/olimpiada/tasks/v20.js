// Складне · «кури й кролики»: 10 голів і 28 ніг у дворі. Скільки кроликів?
// Розвʼязок: якби всі 10 були курми — 20 ніг; кожен кролик додає ще 2,
// тож (28 − 20) / 2 = 4 кролики (16 ніг) і 6 курей (12 ніг).
import { svg, circle, rect, poly, line, text, C, INK } from '../art.js';

// Еліпс — в art.js його немає, тому описаний тут: rot — поворот у градусах навколо центра.
const ellipse = (cx, cy, rx, ry, fill, rot = 0, sw = 3) =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" stroke="${INK}" stroke-width="${sw}"${rot ? ` transform="rotate(${rot} ${cx} ${cy})"` : ''}/>`;

const GROUND = 166; // усі ноги стоять на одній лінії землі

// Нога з лапкою: від низу тулуба до землі.
const leg = (xTop, yTop, xFoot) => `${line(xTop, yTop, xFoot, GROUND, 3)}${line(xFoot - 5, GROUND, xFoot + 7, GROUND, 3)}`;

// Курка: ліворуч, дивиться на табличку.
const chicken = [
  poly([[30, 104], [6, 86], [26, 114]], C.orange, 2), // хвіст — 2 пірʼїни
  poly([[30, 114], [2, 108], [28, 124]], C.orange, 2),
  ellipse(58, 116, 32, 22, C.yellow), // тулуб
  ellipse(54, 118, 15, 9, C.orange, -15, 2), // крило
  poly([[80, 82], [84, 70], [89, 79], [94, 66], [99, 79], [104, 72], [105, 84]], C.red, 2), // гребінець
  circle(92, 93, 14, C.yellow), // голова
  poly([[105, 90], [120, 95], [105, 100]], C.orange, 2), // дзьоб
  circle(104, 104, 3.5, C.red, 1.5), // борідка
  circle(96, 90, 2.5, INK, 0), // око
  leg(50, 137, 48),
  leg(68, 137, 70),
  text(58, 193, '2 ноги', 20),
].join('');

// Кролик: праворуч, довгі вуха, 4 ноги.
const rabbit = [
  circle(256, 112, 9, C.white, 2.5), // хвостик за тулубом
  ellipse(296, 120, 38, 24, C.gray), // тулуб
  ellipse(322, 62, 7, 22, C.gray, -12), // вухо
  ellipse(322, 64, 3.5, 15, C.pink, -12, 0),
  ellipse(339, 64, 7, 22, C.gray, 12), // вухо
  ellipse(339, 66, 3.5, 15, C.pink, 12, 0),
  circle(330, 98, 16, C.gray), // голова
  circle(335, 95, 2.5, INK, 0), // око
  circle(345, 101, 3, C.pink, 1.5), // ніс
  leg(270, 143, 266),
  leg(284, 143, 282),
  leg(306, 143, 304),
  leg(320, 143, 322),
  text(296, 193, '4 ноги', 20),
].join('');

// Табличка посередині: що відомо разом.
const sign = [
  line(182, 140, 182, GROUND, 4),
  rect(126, 56, 112, 84, C.paper, 10), // лівий край 126 — проміжок від дзьоба (120), правий 238 — від хвостика кролика
  text(182, 92, '10 голів', 22),
  text(182, 124, '28 ніг', 22),
].join('');

const art = svg(360, 200, [
  line(6, GROUND, 354, GROUND, 3, C.green), // земля
  chicken,
  sign,
  rabbit,
].join(''));

export const task = {
  id: 'v20',
  tier: 3,
  q: 'У дворі бігають кури й кролики. Разом у них 10 голів і 28 ніг. Скільки у дворі кроликів?',
  art,
  options: ['3', '4', '5', '6'],
};
