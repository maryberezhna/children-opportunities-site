// Складне · монети: по 2 грн і по 5 грн, разом 6 монет на 21 грн.
// Розвʼязок: якщо всі 6 по 2 грн — це 12 грн; бракує 9 грн, кожна заміна
// 2 → 5 додає 3 грн, отже замін 3. Перевірка: 3 × 5 + 3 × 2 = 21.
// Пастки: «2» (половина монет навмання), «4» або «5» (підганяють під 21 без 6 монет).
import { svg, circle, rect, path, text, C, INK } from '../art.js';

// Еліпса в art.js немає — описуємо локально, у тому ж стилі (обведення INK).
const ellipse = (cx, cy, rx, ry, fill, sw = 3) =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" stroke="${INK}" stroke-width="${sw}"/>`;
const dot = (cx, cy, r) => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${INK}"/>`;

// Скарбничка-свинка зліва: тулуб-еліпс, вухо, пʼятачок, ніжки, хвостик, щілина зверху.
const PX = 88; // центр тулуба
const PY = 78;
const piggy = [
  rect(56, 106, 20, 22, C.pink, 6), // ніжки — перед тулубом, щоб він їх прикрив зверху
  rect(102, 106, 20, 22, C.pink, 6),
  path('M 32 70 q -14 -8 -6 -20 q 6 -8 12 -2'), // хвостик
  path('M 114 52 Q 118 24 134 28 Q 146 34 142 56 Z', C.pink), // вухо — округле, щоб не було схоже на ковпачок
  ellipse(PX, PY, 58, 38, C.pink),
  rect(70, 34, 34, 8, INK, 4, 0), // щілина для монет
  dot(122, 68, 4), // око
  ellipse(144, 86, 13, 10, '#ffb3d6'), // пʼятачок
  dot(140, 86, 2), dot(148, 86, 2),
].join('');

// Монета: кружечок з обідком, номінал великими цифрами і «грн» дрібно під ним.
const coin = (cx, cy, fill, label) => [
  circle(cx, cy, 34, fill),
  circle(cx, cy, 27, fill, 1.5),
  text(cx, cy + 6, label, 30),
  text(cx, cy + 22, 'грн', 11, INK, 'middle', 600),
].join('');

// Табличка з умовою: 6 монет = 21 грн.
const sign = [
  rect(70, 140, 220, 46, C.paper, 10),
  text(180, 171, '6 монет = 21 грн', 22),
].join('');

const art = svg(360, 200, [piggy, coin(205, 72, C.yellow, '2'), coin(290, 72, C.orange, '5'), sign].join(''));

export const task = {
  id: 'v23',
  tier: 3,
  q: 'У скарбничці лежать монети по 2 грн і по 5 грн: разом 6 монет на 21 грн. Скільки там монет по 5 грн?',
  art,
  options: ['2', '3', '4', '5'],
};
