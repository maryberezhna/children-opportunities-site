-- Доміграція #138 (застосована до прод-бази 01.09.2026 через MCP; файл — для
-- історії та відтворюваності). Перша чистка (20260830) звузила схему
-- видобування до enum online/offline/hybrid і прибрала явне сміття, але 66
-- «людських» значень («Офлайн, Київ», «Онлайн / офлайн», «Заявка онлайн»)
-- лишились у старих записах. Нові записи чисті — текла лише спадщина.
-- Маппінг літеральний, не регекспний: усі 66 значень переглянуто очима.
-- «Онлайн-подача»/«Заявка онлайн» свідомо йдуть у NULL — спосіб подачі
-- заявки не є форматом події.
UPDATE opportunities SET format = CASE
  WHEN format IN ('online','offline','hybrid') THEN format
  WHEN format ~* 'подач|заявк|application' THEN NULL
  WHEN format IN ('Онлайн','Онлайн, Україна','Онлайн (App Store, Google Play)',
    'Онлайн/мобільний','Онлайн (EOlymp)','online webinar','Брошура + онлайн')
    THEN 'online'
  WHEN format ~* 'гібрид|hybrid' THEN 'hybrid'
  WHEN format IN ('Онлайн / офлайн','Україна / онлайн','online/offline',
    'offline/online','Онлайн + офлайн','online_and_offline',
    'Онлайн + офлайн самміт (NASA)','Офлайн (міста України) + онлайн',
    'Онлайн → Лондон','Онлайн + школи','online та очно','Офлайн/онлайн, Київ',
    'Онлайн + Нью-Йорк','Онлайн + США','Онлайн+CERN','Онлайн + Офлайн (Харків)',
    'online + offline','офлайн та онлайн','Онлайн + виставка Лондон',
    'Онлайн + Лондон') THEN 'hybrid'
  WHEN format ~* '^офлайн' THEN 'offline'
  ELSE NULL
END
WHERE format IS NOT NULL;
