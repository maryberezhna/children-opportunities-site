-- Місто за замовчуванням для фізично прив'язаних джерел.
--
-- 186 із 457 активних записів не мають міста. Здебільшого це правильно —
-- онлайн-курси міста не мають. Але «Місце Сили» це київський простір, у
-- якого 15 записів із 15 приїхали без міста, хоч у тексті стоїть «Київ»:
-- модель його стабільно не витягує. Місто — головний фільтр на сайті, тож
-- без нього запис для людини з іншого міста просто не існує.
--
-- Фолбек застосовується лише коли екстракція не дала міста І запис не
-- онлайн (див. process_pending у scraper/main.py).

update sources
set config = coalesce(config, '{}'::jsonb) || '{"default_city": "Київ"}'::jsonb
where name in (
  'Місце Сили (Клуб Добродіїв)',
  'ЦПР Святошинського району (cprs.kiev.ua)'
);

