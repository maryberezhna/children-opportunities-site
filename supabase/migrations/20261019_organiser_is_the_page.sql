-- «Організатор» на картці — сторінка організатора, а не те, як запис до нас
-- потрапив.
--
-- Марія 19.10.2026, побачивши на сторінці можливості рядок
-- «ОРГАНІЗАТОР · Пропозиція від організатора»: «що це за бред, треба
-- сторінка організатора».
--
-- Пропозиції з поп-апа підписувались цим рядком у source (див.
-- scraper/process_suggestions.py, source_label). Але source — публічна
-- назва організатора на сторінці можливості (lib/opportunity-facts.js), а
-- походження запису живе в origin. Родина бачила службову позначку замість
-- сайту, на який іде подавати заявку.
--
-- Тут виправляємо вже наявні записи: беремо хост із source_url у тому ж
-- вигляді, що й решта джерел (без схеми, без www, без шляху).
update opportunities
set source = regexp_replace(split_part(split_part(source_url, '//', 2), '/', 1), '^www\.', ''),
    updated_at = now()
where source = 'Пропозиція від організатора'
  and source_url is not null
  and split_part(split_part(source_url, '//', 2), '/', 1) <> '';
