-- ============================================================================
-- Вимір міжнародності
--
-- Головний акцент продукту — міжнародні можливості, а визначити їх було ні з
-- чого. Поле countries мало ["ua"] у 677 записах із 690, включно з «FLEX
-- Program — стипендія США», «UWC Changshu China» і «Молодіжний обмін Erasmus+
-- в Греції»: промпт нормалізатора наказував ставити ua за замовчуванням, коли
-- джерело українське. Єдиним слідом закордону лишалося значення «Міжнародні»,
-- яке протекло в поле МІСТ — 30 записів.
--
-- Тепер два незалежні виміри:
--   countries        — де дитина фізично перебуватиме (порожньо, якщо онлайн)
--   is_international — можливість міжнародного рівня, незалежно від формату
--
-- Це саме два, а не один: онлайн-конкурс від японського організатора —
-- міжнародний, але їхати нікуди не треба. Одна мітка на обидва випадки
-- або ховала б міжнародні можливості, або обіцяла б поїздку, якої немає.
-- ============================================================================

alter table opportunities
  add column if not exists is_international boolean not null default false;

-- Часткові індекси: вибірка міжнародних — головний сценарій, а не рідкісний.
create index if not exists opportunities_international_idx
  on opportunities (is_international)
  where is_international;

-- Стартове значення з того сліду, що вцілів. Решту дозаповнює
-- scraper/backfill_geo.py, який питає модель по вже збереженому тексту.
update opportunities
set is_international = true
where cities @> array['Міжнародні'];

comment on column opportunities.is_international is
  'Можливість міжнародного рівня: закордонний організатор, учасники з різних '
  'країн або поїздка за кордон. Не плутати з countries — там лише фізичне '
  'місце перебування дитини, і для онлайн-участі воно порожнє.';
