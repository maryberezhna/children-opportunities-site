-- Дата розіграшу чи оголошення результатів — окремий факт, 17.09.2026.
--
-- «10 річних грантів на англійську» (Helen Doron): у пості сказано лише
-- «переможців визначатимуть у прямому ефірі 30 вересня». Екстрактор знав два
-- значення дати — подача і проведення, — тож записав 30 вересня в усі три поля,
-- і в каналі вийшло «Коли: 30 вересня · Заявки до: 30 вересня». Насправді строк
-- подачі не названо, а сама можливість — рік навчання — без дат. Марія: «це
-- якось тупо… як будемо таке записувати».
--
-- Тепер: deadline — лише прямо названий строк подачі; event_* — коли дитина
-- бере участь; results_date — розіграш, оголошення переможців чи шортлиста.
-- Запис без дедлайну закривається після results_date.
alter table opportunities add column if not exists results_date date;
comment on column opportunities.results_date is
  'Дата розіграшу, оголошення переможців чи шортлиста. Не дедлайн подачі й не дата проведення.';
