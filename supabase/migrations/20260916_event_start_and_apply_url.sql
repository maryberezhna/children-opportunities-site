-- Дата початку події та посилання на подачу — 16.09.2026
--
-- Привід. Запис «Malmö 2026 — Регіональна сесія ЄМП Швеції»: у пості джерела
-- прямо написано «6–8 листопада, дедлайн реєстрації 17 вересня». У базі
-- опинилось deadline=2026-09-17 і event_end_date=2026-11-08, а 6 листопада
-- не лягло НІКУДИ — колонки для початку події не існує. Наслідок видно в
-- каналі: whenLine() бачить заповнений event_end_date, вважає запис подією
-- і зшиває дві різні дати в один діапазон «Коли: 17 вересня — 8 листопада».
-- Тобто дедлайн подачі ми показуємо як день, коли подія триває.
--
-- Корінь глибший за один запис: промпт екстрактора прямо наказував писати
-- ПЕРШУ дату діапазону проведення в `deadline`. Тому в одній колонці лежать
-- дві різні речі — «останній день подачі» і «перший день події», — і жоден
-- споживач (пост, картка, JSON-LD, кнопка календаря) не може їх розрізнити.
--
-- Масштаб на день міграції, серед 1117 активних:
--   6 записів  — тип-подія з deadline без дати кінця: у каналі пішло
--                «📅 Коли: <дедлайн подачі>». Усі шість уже опубліковані,
--                усі шість — закордонні (SHAD, MIT Launch, CISV, GYLC,
--                Iowa Young Writers', All-American Film Festival).
--  26 записів  — обидві дати заповнені: показуємо вигаданий діапазон.
--                Найдовший — UWC: «Коли: 7 жовтня 2026 — 31 серпня 2027».
--  17 записів  — лише кінець події, без початку.
--  43 з 1117   — усе, що взагалі знає бодай щось про дати проведення (3.8%).
--
-- ── event_start_date ────────────────────────────────────────────────────────
-- Перший день проведення. Разом з event_end_date дає чесний діапазон «коли»,
-- а deadline повертає собі єдине значення — «останній день подачі».
alter table opportunities add column if not exists event_start_date date;

create index if not exists idx_opportunities_event_start
  on opportunities (event_start_date)
  where event_start_date is not null;

-- Початок не може бути пізніше за кінець: зворотний діапазон означає, що в
-- одну з колонок знову потрапив дедлайн. Хай падає голосно в лог конвеєра,
-- як уже падають format і cost_type (сітка констрейнтів від 01.09.2026).
alter table opportunities drop constraint if exists opportunities_event_range;
alter table opportunities
  add constraint opportunities_event_range
  check (
    event_start_date is null
    or event_end_date is null
    or event_start_date <= event_end_date
  );

-- ── apply_url ───────────────────────────────────────────────────────────────
-- Адреса, за якою РОДИНА ПОДАЄ ЗАЯВКУ, коли вона не збігається з source_url.
-- У пості про Мальме це https://forms.gle/… — єдине, що людині насправді
-- потрібне, і саме воно не збереглося. Зараз source_url у 64 активних
-- записів веде на пост у Telegram, а не на організатора чи форму: людина
-- приходить із каталогу в чужий канал і далі шукає сама.
--
-- Окремою колонкою, а не заміною source_url: source_url лишається тим, ЗВІДКИ
-- ми взяли запис (на ньому тримаються дедуплікація за canonical_url,
-- перевірка живих посилань і звірка джерел), а apply_url — тим, КУДИ йти
-- людині. Це різні адреси з різним часом життя.
alter table opportunities add column if not exists apply_url text;

comment on column opportunities.event_start_date is
  'Перший день проведення датованої події. deadline — це подача, не початок.';
comment on column opportunities.apply_url is
  'Пряме посилання на подачу заявки (форма, реєстрація), якщо воно не збігається з source_url.';
