-- Припущення про час має бути позначене як припущення — 20.09.2026.
--
-- 986 активних записів не мають жодної дати, 902 з них тримаються на
-- recurrence. У 610 «набір постійний» — це не факт зі сторінки, а правило за
-- замовчуванням для гуртків; ще 749 отримали ongoing масовою дією 11.09 «за
-- типом». Відрізнити їх від записів, де постійність прочитана в тексті з
-- цитатою, було ніяк — саме тому «Літня ІТ-школа Star for Life» прожила на
-- сайті місяць після кінця навчання і пішла в канал 20.09.
--
-- Наслідки позначки: планова перевірка приходить за 30 днів замість 120, а
-- ворота публікації в канал не вважають такий запис вічно відкритим.
alter table opportunities
  add column if not exists timing_assumed boolean not null default false;

comment on column opportunities.timing_assumed is
  'true — вид у часі (timing_kind/recurrence) поставлено за замовчуванням, без цитати з джерела. Такий запис перевіряється частіше й не вважається вічно відкритим.';

-- Бекфіл за слідами в admin_comment: обидві дії лишали свій підпис.
update opportunities
set timing_assumed = true
where timing_assumed = false
  and (admin_comment ilike '%вид: постійна — гурток%'
       or admin_comment ilike '%проставлено ongoing за типом%');
