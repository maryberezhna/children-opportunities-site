--
-- Навіщо: не для добору — можливостей саме для дівчат у каталозі одиниці
-- (на 22.10.2026 одна з ~610), — а для виміру. Скільки дівчат узагалі
-- доходить до можливостей і що їм підбирається, в Україні не міряє ніхто.
--
-- Поле НЕОБОВ'ЯЗКОВЕ: у боті є кнопка «Не вказувати», і тоді лишається NULL.
alter table plus_children
  add column if not exists gender text
  check (gender in ('girl', 'boy'));

comment on column plus_children.gender is
  'girl | boy | NULL — необов''язково, кнопка «Не вказувати» в анкеті бота';
