-- Пів року замість року (Марія, 24.09.2026: «у мене не буде річної підписки,
-- зроби піврічну»; ціна 549 грн — 27.09.2026).
-- Промокод діє на перший платіж кожного плану, тож для піврічного потрібна своя
-- сума. Частка та сама, що була на рік: 799 / 999 = 80% → 549 × 0,8 ≈ 439.
-- yearly_amount лишаємо: річних рахунків більше не створюємо, але колонка
-- нічого не ламає, а історію видно.
alter table public.plus_promo_codes
  add column if not exists halfyear_amount numeric(10, 2);

update public.plus_promo_codes
   set halfyear_amount = 439,
       note = 'Перші користувачі: місяць 1 грн замість 119, пів року 439 замість 549'
 where code = 'first';
