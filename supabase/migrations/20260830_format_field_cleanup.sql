-- ============================================================================
-- Поле format: прибрати накопичене сміття
--
-- format показується на картці як «Онлайн» / «Наживо» / «Онлайн і наживо»
-- (lib/labels.js → formatLabel). У схемі видобування воно було оголошене просто
-- рядком, без переліку — на відміну від сусіднього aid_type. Тож модель писала
-- туди назву джерела («gurtok.org»), тип можливості («olympiad»), спосіб подачі
-- («Через Дію») і просто технічне сміття («json», «text»).
--
-- 74 активні записи, 37 різних значень. Людям це не витікало: formatLabel
-- повертає null на все, що не онлайн/офлайн/гібрид, тож картки просто не
-- показували формат. Але поле в такому стані не годиться ні для фільтра, ні
-- для чогось іще.
--
-- Enum у scraper/normalizer.py закриває джерело — без нього сміття повернулося
-- б із наступним скрапом. Ця міграція прибирає те, що вже накопичилось.
-- ============================================================================

-- 1. Гуртки. Майже все сміття прийшло з gurtok.org, де кожен запис — фізичний
--    гурток із постійним набором за адресою. Формат там завжди наживо.
update opportunities
set format = 'offline'
where opportunity_type = 'club'
  and format is not null
  and lower(format) !~ 'онлайн|online|дистанц'
  and lower(format) !~ 'офлайн|offline|наживо'
  and lower(format) !~ 'гібрид|hybrid';

-- 2. Прямі синоніми «наживо», які регулярка не ловила.
update opportunities
set format = 'offline'
where lower(format) in ('in-person', 'в-очне', 'очно');

-- 3. Решта: типи можливостей, спосіб подачі, місце проведення, технічне сміття.
--    Інформації про формат у них немає — null чесніше за здогадку.
update opportunities
set format = null
where format is not null
  and lower(format) !~ 'онлайн|online|дистанц'
  and lower(format) !~ 'офлайн|offline|наживо'
  and lower(format) !~ 'гібрид|hybrid';
