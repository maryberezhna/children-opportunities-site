-- Лист відправнику, коли його можливість уже на сайті.
--
-- process_suggestions.py відповідав одразу: «у черзі на перевірку» або «уже є
-- на платформі». Про саму публікацію — через день-два, після модерації —
-- відправник не дізнавався. 21.09.2026 Марія попросила слати окремий лист
-- «опубліковано» з пропозицією «Топ тижня» (500 грн) — автоматично.
--
-- published_letter_at — коли відправнику пішов лист, що його можливість на
-- сайті: «опубліковано» або «уже є на платформі». Порожнє — ще не пішов, і
-- прохід notify_published спробує, щойно запис стане active.

alter table opportunity_suggestions
  add column if not exists published_letter_at timestamptz;

-- Наявні рядки: їхні можливості опубліковані ще до цього листа (Seniv Studio
-- 13 і 15.09, решта — наше дослідження без пошти). Лист через тиждень після
-- публікації був би дивним, а Seniv Studio Марія відповіла сама 21.09.2026 —
-- тож позначаємо їх як уже закриті, щоб перший прохід нікому не писав.
update opportunity_suggestions
set published_letter_at = now()
where published_letter_at is null
  and status in ('imported', 'added', 'duplicate');
