-- ============================================================================
-- Під карткою в добірці — «👍 Цікаво», а не «✍️ Подаюсь» — 27.09.2026
--
-- Марія, побачивши картку в боті: «тут має бути цікаво чи не цікаво, і якщо
-- людина натиснула цікаво, то ми будемо запитувати, чи вона подавалася».
--
-- Кнопка «✍️ Подаюсь» просила рішення, якого в людини ще немає: вона щойно
-- побачила назву й дедлайн і не знає, чи подаватиметься. Сторінка /plus,
-- пост у каналі й політика приватності весь цей час обіцяли «Цікаво / Не
-- цікаво» — бот єдиний просив інше.
--
-- Нова стадія 'interested' окремо від 'applying' саме тому, що це різні речі:
-- «цікаво» — це інтерес, «подаюсь» — заявка. Записати людині «подаюсь» за
-- одне натискання означало б вигадати за неї. Старі рядки 'applying'
-- лишаються як є — їх поставили люди, і переписувати їхню відповідь не можна.
--
-- Застосувати руками через конектор Supabase: скрипти міграції не котять.
-- ============================================================================

do $$
declare c record;
begin
  for c in
    select conname
    from pg_constraint
    where conrelid = 'plus_applications'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%stage%'
  loop
    execute format('alter table plus_applications drop constraint %I', c.conname);
  end loop;
end $$;

-- Повний перелік стадій після 27.09.2026:
--   interested — «👍 Цікаво» під карткою (єдине, що зараз ставить бот);
--   applying   — «✍️ Подаюсь», кнопка 20–27.09.2026. Нових не буде, старі живуть;
--   asked      — бот спитав «чи подавалися», відповіді ще немає;
--   used       — «Так, подавалися»;
--   not_used   — «Ні»;
--   applied / skipped / accepted — лишаються з 20.09.2026, нічим не займані.
alter table plus_applications
  add constraint plus_applications_stage_check
  check (stage in ('interested', 'applying', 'asked', 'applied', 'skipped',
                   'accepted', 'used', 'not_used'));
