-- Країна можливості — вимір, якого бракувало для діаспорного напряму.
--
-- Досі геолокація трималась лише на `cities`, і це працювало, поки каталог був
-- суто український. Для дітей, які живуть у Польщі, Німеччині чи Чехії, місто
-- без країни неоднозначне (Львів є і в Україні, і в назвах організацій), а
-- фільтрувати «покажи все для Польщі» не було чим.
--
-- Формат дзеркалить `cities`: text[], бо одна програма може покривати кілька
-- країн (онлайн-школа для діаспори), і NULL означає «не вказано», а не
-- «Україна» — заповнюємо явно.
--
-- Значення — ISO 3166-1 alpha-2 у нижньому регістрі: 'ua', 'pl', 'de', 'cz'.
-- Коди, а не назви, саме щоб не повторити історію з `categories`, де LLM
-- нагенерував 200 варіантів чотирма мовами.

alter table opportunities
  add column if not exists countries text[];

comment on column opportunities.countries is
  'ISO 3166-1 alpha-2, нижній регістр: ua, pl, de, cz. NULL = не визначено.';

create index if not exists opportunities_countries_gin
  on opportunities using gin (countries);

-- Наявні записи: усе, що вже в базі, зібране з українських джерел.
-- Проставляємо 'ua' тільки там, де країна ще не задана.
update opportunities
set countries = array['ua']
where countries is null;
