"""Агрегатори — де ЗНАХОДИТИ можливості (Марія, 12.10.2026: «агрегатори самі
цінні для нас, веди список агрегаторів, адже у них багато крутих
можливостей»).

Агрегатор — не можливість: загальна сторінка програми, добірка чи каталог на
картку не йде, джерелом стає сторінка організатора конкретної програми. Але
як місце пошуку агрегатор найцінніший — тому discover-агент отримує цей
список як підказку, де дивитись.

Людський список із поясненнями й станом — Notion «🧭 Агрегатори можливостей —
звідки беремо». Новий агрегатор → рядок і там, і тут.
"""
from __future__ import annotations

# (домен, що там шукати). Ті, що вже мають власний скрапер у `sources`
# (Eurodesk, Erasmus+ UA, House of Europe, Дія.Освіта), тут не дублюємо.
AGGREGATORS: tuple[tuple[str, str], ...] = (
    ("youth.europa.eu", "волонтерство й обміни European Solidarity Corps"),
    ("erasmus-plus.ec.europa.eu", "конкретні молодіжні обміни Erasmus+"),
    ("prostir.ua", "конкурси, гранти й програми громадських організацій"),
    ("osvita.ua", "конкурси й олімпіади для школярів"),
    ("znayshov.com", "конкурси й ресурси для школярів"),
    ("dityvmisti.ua", "табори й канікулярні програми"),
    ("childcamp.com.ua", "табори"),
    ("uboost.study", "навчання й програми за кордоном"),
    ("opportunitiescorners.com", "міжнародні конференції, стипендії, конкурси"),
    ("opportunitydesk.org", "міжнародні можливості для молоді"),
)


def prompt_block() -> str:
    """Блок для промпту discover-агента: де шукати й що ставити в url."""
    lines = "\n".join(f"  · {d} — {what}" for d, what in AGGREGATORS)
    return (
        "ДЕ ШУКАТИ. Агрегатори — найкраще місце, щоб ЗНАЙТИ можливості:\n"
        f"{lines}\n"
        "Знайшов можливість на агрегаторі — відкрий сайт організатора і в url\n"
        "постав ЙОГО сторінку цієї програми. Сам агрегатор, добірка чи загальна\n"
        "сторінка програми («Erasmus+ — молодіжні обміни») — не url.\n"
    )
