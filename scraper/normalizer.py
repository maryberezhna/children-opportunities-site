# Наскільки давньою може бути дата поточного року, щоб усе ще вважатись
# «щойно минулою», а не торішньою. Півроку — компроміс для межі грудень/січень:
# оголошення в грудні про «15 січня» має означати січень НАСТУПНОГО року.
_SNAP_BACKSTOP_DAYS = 180



def strip_invented_repeat(data: dict, haystack: str) -> dict:
    """«Періодична» і «щороку» — це факт зі сторінки, а не здогад.

    20.09.2026: курс AI Kids Academy — один набір на три місяці — приїхав як
    periodic + recurrence=annual, хоч у статті немає ні слова про повторення.
    Вид у шляху екстракції ніхто не звіряв із текстом (на відміну від
    classify_timing.py), тож модель могла пообіцяти читачеві «щороку» там, де
    набір один.

    Знімаємо обидва поля — запис піде людині, бо без періодичності в нього не
    лишається чим закритись. Це дорожче за тихий здогад, але здогад тут коштує
    довіри: родина чекатиме наступного року, якого не буде.
    """
    if data.get("opportunity_type") in PERIODIC_BY_DEFINITION:
        return data
    if has_repeat_signal(haystack):
        return data
    stripped = []
    if data.get("timing_kind") == "periodic":
        data["timing_kind"] = None
        stripped.append("вид «періодична»")
    if data.get("recurrence") == "annual":
        data["recurrence"] = None
        stripped.append("recurrence=annual")
    if stripped:
        note = ("знято " + " і ".join(stripped)
                + ": у тексті немає ознак повторюваності — перевірити")
        data["admin_comment"] = ((data.get("admin_comment") or "") + " " + note).strip()
    return data


def published_date(raw_text: str) -> str | None:
    """Дата публікації з першого рядка сирця (raw_store.with_published)."""
    m = re.match(r"^Дата публікації: (\d{4}-\d{2}-\d{2})", raw_text or "")
    return m.group(1) if m else None


def _fix_invented_years(data: dict, haystack: str, today_iso: str,
                        published_iso: str | None = None) -> dict:
    """Полагодити дати, яким модель дописала чужий рік.

    Модель регулярно ставить до дати без року рік із минулого — попри пряме
    правило в промпті. За два тижні так з'явилось 13 «протермінованих»
    записів, і в усіх день і місяць збігались із датою додавання, а рік — ні:
        «13 серпня» у пості від 15.08.2026 → deadline 2024-08-13
        «20 серпня» у пості від 15.08.2026 → deadline 2025-08-20
    Це не старі можливості, а живі з підробленим роком.

    Критерій детермінований, без здогадок: якщо дата в минулому І цього року
    НЕМАЄ в тексті дослівно — рік вигадали, підставляємо рік публікації.
    Якщо рік у тексті є, дату не чіпаємо: вона чесно торішня.
    """
    # Рік підставляємо відносно дати ПУБЛІКАЦІЇ, коли джерело її знає: пост від
    # 15 серпня, розмічений у вересні, мав би інакше отримати рік «сьогодні».
    anchor = published_iso or today_iso
    for key in ("deadline", "event_start_date", "event_end_date", "results_date"):
        v = data.get(key)
        if not v or v >= today_iso:
            continue
        year = v[:4]
        if year in haystack:
            continue  # рік справді написаний у тексті — дата чесна
        fixed = _snap_year_to_now(v, anchor)
        if not fixed or fixed == v:
            continue
        data[key] = fixed
        data["admin_comment"] = (
            (data.get("admin_comment") or "")
            + f" auto: {key} {v} → {fixed}, року {year} у тексті немає "
              "(LLM його вигадав) — перевір дату"
        ).strip()
    return data


def _snap_year_to_now(date_iso: str, today_iso: str) -> str | None:
    """Підставити рік ПУБЛІКАЦІЇ до дати, якій модель дописала чужий рік.

    День і місяць у таких випадках правильні — помиляється саме рік, тож
    беремо поточний. Свідомо НЕ шукаємо «найближчу майбутню» дату: лекція
    13 серпня, яку витягли 15 серпня, справді вже минула, і чесна відповідь —
    13 серпня цього року (запис піде в closed), а не вигаданий дедлайн через рік.

    Виняток — межа року: якщо дата поточного року опинилась більш ніж за
    пів року позаду, це радше про наступний рік («15 січня» в грудневому пості).
    """
    try:
        d = datetime.strptime(date_iso, "%Y-%m-%d").date()
        today = datetime.strptime(today_iso, "%Y-%m-%d").date()
    except ValueError:
        return None
    for year in (today.year, today.year + 1):
        try:
            candidate = d.replace(year=year)
        except ValueError:
            continue  # 29 лютого у невисокосному році
        if (today - candidate).days <= _SNAP_BACKSTOP_DAYS:
            return candidate.isoformat()
    return None


class Normalizer:
    def __init__(self):
        self.client = api_guard.client(api_key=os.environ["ANTHROPIC_API_KEY"])
        self.model = "claude-haiku-4-5-20251001"
        # Помилки API збираємо, щоб денний звіт показав їх окремим блоком.
        # Без цього «0 збережено» два тижні виглядало як норма, поки насправді
        # кожен виклик падав із «credit balance too low».
        self.api_failures = 0
        self.last_api_error = None
        # Кеш-статистика за запуск: якщо cache_read лишається нулем при
        # сотнях викликів — кешування зламалось (див. _call_api) і ми знову
        # платимо повну ціну за той самий префікс.
        self.cache_read_tokens = 0
        self.cache_write_tokens = 0
        self.uncached_input_tokens = 0

    def normalize(self, raw_text: str, source: str, source_url: str,
                  raw_title: Optional[str] = None) -> Optional[dict]:
        # Причина останнього відхилення. Без неї 510 із 519 відсіяних записів
        # лежали в raw_items із порожнім last_error: неможливо було ні довести,
        # що фільтр працює, ні помітити, коли він почне різати живе.
        self.last_reject_reason = None
        # Машинні поля відмови (20.09.2026): раніше і причина, і оцінка жили
        # текстом усередині last_error, тож їх не можна було ні порахувати, ні
        # відсортувати, ні тюнити поріг. Тепер у raw_items є колонки.
        self.last_reject_code = None
        self.last_confidence = None
        try:
            today_iso = datetime.utcnow().date().isoformat()
            published_iso = published_date(raw_text)
            published_line = f"Опубліковано: {published_iso}\n" if published_iso else ""
            user_msg = f"""Сьогодні: {today_iso}
{published_line}
Джерело: {source}
URL: {source_url}
Заголовок: {raw_title or '(немає)'}

ТЕКСТ:
{raw_text[:6000]}

Витягни дані через extract_opportunity."""

            response = self._call_api(user_msg)

            tool_use = next(
                (b for b in response.content
                 if b.type == "tool_use" and b.name == "extract_opportunity"),
                None
            )
            if not tool_use:
                self.last_reject_reason = "не можливість для дитини (модель не витягла даних)"
                self.last_reject_code = "not_child"
                return None

            data = tool_use.input
            self.last_confidence = data.get("confidence")
            if data.get("confidence", 0) < 0.5:
                conf = data.get("confidence", 0)
                logger.info(f"Low confidence, skipping: {source_url}")
                self.last_reject_reason = f"низька впевненість моделі ({conf})"
                self.last_reject_code = "low_confidence"
                return None

            data = _sanitize(dict(data))
            title = data["title"]
            data["slug"] = self._make_slug(title, source)
            data["content_hash"] = self._make_hash(title, source_url)
            data["source"] = source
            data["source_url"] = source_url
            data["canonical_url"] = canonical_url(source_url)
            data.pop("confidence", None)

            # Стан набору за текстом сторінки: закрито/протерміновано → запис
            # одразу closed, а не «активний до ручної перевірки». Колонки
            # enrollment_status в базі немає — сигнал мапиться на status.
            enrollment = data.pop("enrollment_status", "unknown")
            if enrollment in ("closed", "expired") and data.get("status") != "draft":
                data["status"] = "closed"

            # Рядок «Дата публікації» не рахується текстом джерела: інакше рік
            # публікації завжди «є в тексті», і вигаданий рік не виправлявся б.
            body = re.sub(r"^Дата публікації: \d{4}-\d{2}-\d{2}\s*", "", raw_text or "")
            data = _fix_invented_years(
                data, f"{body} {raw_title or ''}", today_iso, published_iso)

            data = strip_invented_repeat(data, f"{body} {raw_title or ''}")

            # Дати в минулому — запобіжник, незалежний від LLM: подія, що вже
            # відбулась, або дедлайн, що минув, не сміють дати active-запис
            # (кейс «ATLAS Weekend висів активним через місяць після події»).
            for key in ("deadline", "event_end_date"):
                v = data.get(key)
                if v and v < today_iso and data.get("status") != "draft":
                    data["status"] = "closed"

            # Архівний мотлох. Дата в минулому, рік у тексті стоїть — значить
            # це справді торішній або позаторішній запис. Зберігати сенс має
            # лише те, що може ожити наступного сезону (recheck_at ~11 міс).
            # Усе старше року — артефакт архівної сторінки: у базу потрапив
            # мовний табір із дедлайном 2017-06-20. Такому в каталозі не місце.
            cutoff = (datetime.utcnow().date() - timedelta(days=400)).isoformat()
            for key in ("deadline", "event_end_date"):
                v = data.get(key)
                if v and v < cutoff:
                    logger.info(
                        "Відхилено як архівне: %s=%s (старше 400 днів) — %s",
                        key, v, source_url,
                    )
                    self.last_reject_reason = f"архівне: {key}={v} (старше 400 днів)"
                    self.last_reject_code = "off_topic"
                    return None

            # Симетрія: відкритий набір без минулих дат ОЖИВЛЯЄ авто-закритий
            # запис — так сезонна перевірка (recheck_at через ~11 місяців)
            # повертає торішні фестивалі/табори з новою програмою. Модераторські
            # записи захищає verified_at у db.upsert_opportunity.
            if enrollment == "open" and "status" not in data:
                data["status"] = "active"

            return data

        except Exception as e:
            logger.error(f"Normalize failed for {source_url}: {e}")
            self.api_failures += 1
            self.last_api_error = str(e)[:300]
            raise NormalizeError(str(e)[:300]) from e

    def _call_api(self, user_msg: str):
        """Виклик Haiku з retry: 429/5xx/таймаути — тимчасові, пробуємо ще
        двічі з паузою. Помилки біллінгу і 4xx не ретраяться — це не лікується
        повтором, лише палить час усього нічного запуску."""
        import time as _time
        last_exc = None
        for attempt in range(3):
            try:
                resp = self.client.messages.create(
                    model=self.model,
                    # details підняв стелю відповіді: до 4000 знаків тексту
                    # плюс решта полів. На 1500 модель обривала опис посеред
                    # речення, і весь tool_use приходив невалідним — запис
                    # втрачався цілком, а не лишався без одного поля.
                    max_tokens=4000,
                    # Кеш промпта: префікс tools+system однаковий у КОЖНОМУ
                    # виклику (схема + 6К знаків інструкцій), а за нічний
                    # запуск викликів сотні поспіль. Без cache_control ми
                    # платили за цей префікс повну ціну щоразу; з ним перший
                    # виклик пише кеш (×1.25), решта читає за ~10% ціни.
                    # Брейкпоінт на system покриває і tools — вони рендеряться
                    # перед system у префіксі.
                    system=[{
                        "type": "text",
                        "text": SYSTEM_PROMPT,
                        "cache_control": {"type": "ephemeral"},
                    }],
                    tools=[EXTRACT_TOOL],
                    tool_choice={"type": "tool", "name": "extract_opportunity"},
                    messages=[{"role": "user", "content": user_msg}],
                )
                u = getattr(resp, "usage", None)
                if u is not None:
                    self.cache_read_tokens += getattr(u, "cache_read_input_tokens", 0) or 0
                    self.cache_write_tokens += getattr(u, "cache_creation_input_tokens", 0) or 0
                    self.uncached_input_tokens += getattr(u, "input_tokens", 0) or 0
                return resp
            except anthropic.APIStatusError as e:
                if e.status_code not in (429, 500, 502, 503, 529):
                    raise
                last_exc = e
            except (anthropic.APIConnectionError, anthropic.APITimeoutError) as e:
                last_exc = e
            _time.sleep(2 * (attempt + 1))
        raise last_exc

    # Власна транслітераційна таблиця замість дефолтної поведінки slugify.
    # python-slugify транслітерує кирилицю тим unidecode-пакетом, який
    # ВИПАДКОВО стоїть в оточенні: text-unidecode дає «kvity-peremohy»,
    # Unidecode — «kviti-peremogi». Два запуски в різних оточеннях робили
    # два різні слаги для того самого запису — і дубль у базі (01.09 злито
    # 20 таких пар). Таблиця спрощена офіційна (без позиційних правил
    # «є→ye на початку слова»): для слага важлива детермінованість, не
    # філологічна точність. Наявні слаги не переганяються — це живі URL.
    _UK2LAT = [
        ("зг", "zgh"),
        ("а", "a"), ("б", "b"), ("в", "v"), ("г", "h"), ("ґ", "g"),
        ("д", "d"), ("е", "e"), ("є", "ie"), ("ж", "zh"), ("з", "z"),
        ("и", "y"), ("і", "i"), ("ї", "i"), ("й", "i"), ("к", "k"),
        ("л", "l"), ("м", "m"), ("н", "n"), ("о", "o"), ("п", "p"),
        ("р", "r"), ("с", "s"), ("т", "t"), ("у", "u"), ("ф", "f"),
        ("х", "kh"), ("ц", "ts"), ("ч", "ch"), ("ш", "sh"), ("щ", "shch"),
        ("ь", ""), ("ю", "iu"), ("я", "ia"), ("'", ""), ("ʼ", ""), ("’", ""),
    ]

    @classmethod
    def _make_slug(cls, title: str, source: str) -> str:
        base = slugify(title.lower(), replacements=cls._UK2LAT,
                       max_length=80, word_boundary=True)
        short_hash = hashlib.md5(f"{title}{source}".encode()).hexdigest()[:6]
        return f"{base}-{short_hash}"

    @staticmethod
    def _make_hash(title: str, url: str) -> str:
        """Ключ дедуплікації (upsert on_conflict=content_hash).

        Сама формула живе в hubs.content_hash — одна на всі конвеєри.

        Раніше ключ був title+url — і не працював: назву генерує LLM, тож для
        того самого джерела вона щоразу інша («uBoost Career», «uBoost Career —
        державна програма профорієнтації та навичок для молоді», «uBoost Career
        — державна програма для молоді»). Кожен варіант давав новий хеш і новий
        рядок. У базі назбиралось 8 копій uBoost і 7 українсько-польських
        обмінів.

        Поріг за схожістю назв тут не рятує — виміряно на реальних даних:
            справжні дублі   0.32 – 0.87
            різні можливості 0.42 – 0.94
        «олімпіада з біології» vs «з екології» дає 0.94 і це РІЗНЕ, а
        «uBoost Career» vs його ж довга назва — 0.32 і це ОДНЕ. Діапазони
        перекриваються, отже жоден поріг не розділить.

        Тому ключ — сам URL: він стабільний. Виняток — сторінки-хаби, де на
        одній адресі справді живе багато різних можливостей (перелік олімпіад
        МОН, каталог послуг Дії). Для них лишаємо title+url.
        """
        return hubs.content_hash(title, url)
