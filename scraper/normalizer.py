PAYMENT_TYPES = {"allowance", "support_payment"}


# Опис, у якому модель САМА написала, що сезон чи набір уже позаду.
# 16.09.2026 пошуковий агент поклав у чергу «Bloomsday Young Authors» з описом
# «сезон 2026 року вже завершено»: дати не було, лише «щороку», тож жодна
# перевірка дат не мала з чим порівнювати, а сам текст ніхто не читав.
_OVER = re.compile(
    r"(?:вже|уже)\s+(?:завершен|завершил|минул|минув|відбул|закінч|пройш|закрит)"
    r"|сезон\w*\s+20\d\d[^.]*?(?:завершен|завершил|минув|минул|закінч)"
    r"|(?:набір|реєстраці[юя]|прийом\s+заявок|подач[ау]\s+заявок)\s+"
    r"(?:завершено|закрито|припинено)",
    re.IGNORECASE,
)
# «Сезон 2026 завершено, реєстрація на 2027 відкрита» — живий запис, не минуле.
_STILL_OPEN = re.compile(
    r"відкрит|триває|приймаються|оголошено\s+набір|реєстрація\s+на\s+20\d\d",
    re.IGNORECASE,
)


def summary_says_over(text) -> bool:
    """Чи прямо сказано в описі, що набір або сезон уже завершився."""
    text = text or ""
    return bool(_OVER.search(text)) and not _STILL_OPEN.search(text)


def missing_required(data: dict, age_missing: bool = None) -> list:
    """Чого бракує запису, щоб його можна було показати людині."""
    missing = []
    if age_missing is None:
        age_missing = data.get("age_from") is None or data.get("age_to") is None
    if age_missing:
        missing.append("вік")
    if not data.get("deadline") and not data.get("event_start_date") \
            and not data.get("event_end_date") and not data.get("results_date") \
            and not data.get("recurrence") \
            and data.get("opportunity_type") not in PAYMENT_TYPES:
        missing.append("дата, період або періодичність")
    if data.get("cost_type") not in PUBLISHABLE_COST_TYPES:
        missing.append("вартість")
    if data.get("opportunity_type") not in VALID_OPP_TYPES:
        missing.append("тип")
    # «Де» вважається відомим, якщо є формат, місто, країна або позначка
    # міжнародної: будь-що з цього відповідає батькові, куди йти дитині.
    if not (data.get("format") or data.get("cities") or data.get("countries")
            or data.get("is_international")):
        missing.append("формат або місце (онлайн / офлайн / за кордоном)")
    return missing


# Адреси, які НЕ бувають посиланням на подачу, хоч модель їх туди і кладе:
# чат чи канал організатора, профіль у соцмережі. Сухий прогін перерозмітки
# 16.09.2026 приліпив одне й те саме запрошення в Telegram-чат
# (t.me/+QTt-hFjTfJw0MGNi) до чотирьох різних обмінів Erasmus+ як «форму подачі».
_NOT_APPLY_HOSTS = ("t.me", "telegram.me", "instagram.com", "www.instagram.com")


def valid_apply_url(url, source_url=None):
    """Посилання на подачу або None. Спільне для екстрактора й remark.py."""
    from urllib.parse import urlparse
    url = (url or "").strip()
    if not url.startswith("http"):
        return None
    if source_url and url.rstrip("/") == str(source_url).strip().rstrip("/"):
        return None
    if (urlparse(url).hostname or "").lower() in _NOT_APPLY_HOSTS:
        return None
    return url[:500]


# Держава як той, хто дає підтримку, — а не слово «державний» у назві закладу.
# На 17.09.2026 у базі 28 платних курсів і гуртків «Житомирського державного
# університету»: буквальне правило «є слово державна — безкоштовно» зробило б
# їх усіх безкоштовними.
_STATE_SUPPORT = re.compile(
    r"державн\w*\s+(?:цільов\w*\s+)?(?:підтримк|допомог|програм|виплат|стипенді|"
    r"гарант|соціальн\w*\s+допомог|замовленн|оздоровленн|послуг)"
    r"|за\s+рахунок\s+(?:держав|бюджет|коштів\s+державного)"
    r"|з\s+державного\s+бюджету|держбюджет",
    re.IGNORECASE,
)


def is_state_support(text) -> bool:
    return bool(_STATE_SUPPORT.search(text or ""))


def _apply_state_support_free(data: dict) -> None:
    """Державна підтримка — безкоштовна (рішення Марії 17.09.2026).

    Картка «Державна цільова підтримка для здобуття професійної, фахової
    передвищої та вищої освіти» висіла в модерації з «бракує: вартість»: у
    тексті про гроші ані слова, бо платити за державну підтримку нема за що.
    Порожню вартість заповнюємо; якщо це державна допомога (aid_type), а
    модель поставила «платно», теж виправляємо — з позначкою модератору.
    """
    text = " ".join(str(data.get(k) or "") for k in ("title", "summary", "details"))
    cost = data.get("cost_type")
    if cost == "free":
        return
    if cost is None and (is_state_support(text) or data.get("aid_type")):
        data["cost_type"] = "free"
        note = "auto: державна підтримка — безкоштовно (рішення 17.09.2026)"
    elif cost and data.get("aid_type"):
        data["cost_type"] = "free"
        note = f"auto: державна допомога — безкоштовно, модель поставила {cost} — перевір"
    else:
        return
    data["admin_comment"] = ((data.get("admin_comment") or "") + " " + note).strip()


# «Онлайн» як формат САМОЇ участі. Слова після нього — те, що людина робить:
# школа, курс, заняття, табір. «Онлайн-реєстрація», «онлайн-заявка», «подати
# онлайн» сюди не потрапляють навмисно: це спосіб подати документи, а не
# формат можливості — табір, куди записуються онлайн, лишається табором наживо.
_ONLINE_WHAT = (r"школ|курс|урок|занятт|навчанн|формат|режим|марафон|табір|табор|"
                r"клуб|гурт|лекці|програм|олімпіад|конкурс|інтенсив|вебінар|майстер|"
                r"челендж|хакатон|консультац|студі|академі")
_ONLINE_IN_TEXT = re.compile(
    rf"онлайн[-‑\s]?(?:{_ONLINE_WHAT})"
    rf"|(?:у|в)\s+форматі\s+онлайн"
    rf"|дистанційн\w*\s+(?:{_ONLINE_WHAT})"
    rf"|\bonline[-\s]?(?:school|course|class|lesson|program|camp)",
    re.IGNORECASE)
_ONLINE_TITLE = re.compile(r"^\W*(?:online|онлайн)\b", re.IGNORECASE)
_OFFLINE_IN_TEXT = re.compile(r"\bочн(?:о|ий|і|а|их)\b|офлайн|offline|наживо", re.IGNORECASE)


def _note(data: dict, text: str) -> None:
    data["admin_comment"] = ((data.get("admin_comment") or "") + " " + text).strip()


def _fill_from_text(data: dict, age_missing: bool) -> bool:
    """Порожні поля — з назви й опису (scraper/text_fill.py). Повертає, чи вік
    тепер відомий. Модельна відповідь має пріоритет: правила чіпають лише
    порожнє, і кожне лишає позначку, звідки взялось значення."""
    title = data.get("title") or ""
    text = " ".join(str(data.get(k) or "") for k in ("title", "summary"))

    if age_missing:
        ages = text_fill.age_from_text(text)
        if ages:
            data["age_from"], data["age_to"] = ages
            age_missing = False
            _note(data, f"auto: вік {ages[0]}–{ages[1]} — з тексту")

    if data.get("opportunity_type") not in VALID_OPP_TYPES:
        typ = text_fill.type_from_title(title)
        if typ:
            data["opportunity_type"] = typ
            _note(data, f"auto: тип «{typ}» — з назви")

    if data.get("cost_type") is None:
        cost = text_fill.cost_from_text(text)
        if cost:
            data["cost_type"] = cost
            _note(data, "auto: вартість «" + ("безкоштовно" if cost == "free" else "платно")
                  + "» — прямо в тексті")

    has_dates = any(data.get(k) for k in ("deadline", "event_start_date", "event_end_date",
                                           "results_date"))
    if not has_dates and not data.get("recurrence"):
        if text_fill.recurrence_from_text(text):
            data["recurrence"] = "annual"
            _note(data, "auto: «щороку» — ознака повторення в тексті")

    # Місце: лише коли нічого не відомо й участь не онлайн.
    if data.get("format") != "online" and not data.get("cities") and not data.get("countries"):
        city = text_fill.city_from_text(text)
        if city:
            data["cities"] = [city]
            _note(data, f"auto: місто «{city}» — з тексту")
        else:
            code = text_fill.country_from_text(text)
            if code and code in VALID_COUNTRIES:
                data["countries"] = [code]
                _note(data, f"auto: країна «{code}» — з тексту («в/у/до …»)")
    return age_missing


def _apply_format_from_text(data: dict) -> None:
    """Формат, який прямо написаний у назві чи описі, — факт, а не здогад.

    21.09.2026 у черзі модерації стояла «ТВОЯ ШКОЛА — українська онлайн-школа
    для дітей за кордоном» з «бракує: формат або місце». Модель, що читала
    сторінку, поле format лишила порожнім, хоча слово стоїть у самій назві.
    Такі записи не йшли на сайт і чекали, поки модератор допише очевидне.

    Лише коли модель формату не дала: її відповідь має пріоритет. «Онлайн» і
    «очно» разом — hybrid. Позначка модератору лишається.
    """
    if data.get("format"):
        return
    title = data.get("title") or ""
    text = " ".join(str(data.get(k) or "") for k in ("title", "summary"))
    if not (_ONLINE_TITLE.search(title) or _ONLINE_IN_TEXT.search(text)):
        return
    data["format"] = "hybrid" if _OFFLINE_IN_TEXT.search(text) else "online"
    note = f"auto: формат «{data['format']}» — прямо в назві чи описі"
    data["admin_comment"] = ((data.get("admin_comment") or "") + " " + note).strip()
    # «Онлайн» у cities — теж відповідь на «де», і фільтр міст на сайті її читає.
    if data["format"] == "online" and not data.get("cities"):
        data["cities"] = ["Онлайн"]


def _apply_club_default(data: dict) -> None:
    """Гурток, про набір якого текст мовчить, — постійний (рішення Марії 17.09.2026).

    До 17.09.2026 це «знання» підкладали скрапери гуртків: дописували в сирий
    текст «Набір постійний, дедлайну немає», і модель слухняно читала це як
    факт зі сторінки. Тепер правило стоїть тут, відкрито, і лишає позначку
    модератору, — а скрапери пишуть лише те, що є в джерелі.

    Вид, прочитаний із тексту (періодичний, одноразовий), має пріоритет. А
    recurrence тримаємо в злагоді з видом: на ньому досі тримається вимога
    «дата, період або періодичність».
    """
    kind = data.get("timing_kind")
    has_dates = any(data.get(k) for k in ("deadline", "event_start_date", "event_end_date"))
    if data.get("opportunity_type") == "club" and not kind and not has_dates \
            and not data.get("recurrence"):
        data["timing_kind"] = kind = "permanent"
        # Позначка в базі, а не лише в коментарі: припущення мусить бути
        # видно машині. Такий запис перевіряється частіше і не вважається
        # вічно відкритим там, де ми публікуємо (ворота поста в канал).
        data["timing_assumed"] = True
        note = ("вид: постійна — гурток, текст не каже про сезон набору; "
                "за замовчуванням (рішення 17.09.2026), перевірити")
        data["admin_comment"] = ((data.get("admin_comment") or "") + " " + note).strip()
    if not data.get("recurrence") and not has_dates:
        if kind == "permanent":
            data["recurrence"] = "ongoing"
        elif kind == "periodic":
            data["recurrence"] = "annual"


# Ієрогліфи, які модель зрідка вставляє замість українського слова: «Навчання可а
# офлайн», «для創ення», «##時间розгляду» — сім записів станом на 17.09.2026.
_FOREIGN_SCRIPT = re.compile(r"[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7af]+")


def strip_foreign_script(text):
    """(текст без ієрогліфів, чи щось вирізали)."""
    if not isinstance(text, str):
        return text, False
    cleaned = _FOREIGN_SCRIPT.sub("", text)
    return cleaned, cleaned != text


def _sanitize(data: dict) -> dict:
    """Coerce AI output to values the DB accepts, so a bad field never sinks
    the whole record."""
    stripped = False
    for key in ("title", "summary", "details"):
        data[key], hit = strip_foreign_script(data.get(key))
        stripped = stripped or hit
    if stripped:
        data["admin_comment"] = ((data.get("admin_comment") or "")
                                 + " auto: модель вставила ієрогліфи — вирізано, перевір формулювання").strip()

    for key in ("deadline", "event_start_date", "event_end_date", "results_date"):
        val = data.get(key)
        if val:
            try:
                # Accepts "2026-4-5" too, normalises to "2026-04-05"; rejects word
                # dates like "квітень" / "abril 2024".
                data[key] = datetime.strptime(str(val).strip(), "%Y-%m-%d").date().isoformat()
            except ValueError:
                data[key] = None

    # Перевернутий діапазон події означає, що модель переплутала поля місцями.
    # У базі на це стоїть CHECK (opportunities_event_range), і без обміну тут
    # запис падав би на вставці й зникав — як колись зникали записи з віком
    # поза 0–18. Міняємо місцями, а не відкидаємо: обидві дати справжні.
    start, end = data.get("event_start_date"), data.get("event_end_date")
    if start and end and start > end:
        data["event_start_date"], data["event_end_date"] = end, start

    # Посилання на подачу: лише http(s), не адреса самого джерела і не чат чи
    # соцмережа організатора (див. valid_apply_url).
    data["apply_url"] = valid_apply_url(data.get("apply_url"), data.get("source_url"))

    # details — вільний текст із розміткою; ріжемо по стелі колонки в адмінці.
    details = (data.get("details") or "").strip()
    data["details"] = details[:20000] or None
    # Вік: у базі CHECK 0..18, а LLM іноді віддає верхню межу самої програми
    # («13–19 років» → age_to=19). Раніше такий запис падав на констрейнті і
    # ЗНИКАВ (так загубився набір WonderStage) — тепер просто підрізаємо до
    # нашого діапазону: програма для 13–19 лишається валідною для 13–18.
    # Вік, якого модель не дала, раніше мовчки ставав 0–18 — і доросла
    # програма отримувала дитячий діапазон. Схема ще й змушує модель віддати
    # число в межах 0..18, тож «не знаю» вона висловити не могла. Тепер
    # відсутній вік лишає діапазон 0–18 як технічний, але відправляє запис
    # людині: опублікуватись сам він не може (аудит 11.09.2026).
    age_missing = any(data.get(key) in (None, "") for key in ("age_from", "age_to"))
    for key, default in (("age_from", 0), ("age_to", 18)):
        try:
            val = int(data.get(key, default))
        except (TypeError, ValueError):
            val = default
        data[key] = max(0, min(18, val))
    if data.get("recurrence") not in ("annual", "ongoing"):
        data["recurrence"] = None
    # Вид за часом і місяці сезону (з 17.09.2026, див. scraper/timing.py).
    data["timing_kind"] = clean_kind(data.get("timing_kind"))
    data["season_months"] = (clean_months(data.get("season_months"))
                             if data["timing_kind"] == "periodic" else None)
    _apply_club_default(data)
    if data["age_from"] > data["age_to"]:
        data["age_from"], data["age_to"] = data["age_to"], data["age_from"]

    # cost_type & deadline are nullable — drop unknown values to null.
    if data.get("cost_type") not in VALID_COST_TYPES:
        data["cost_type"] = None
    _apply_state_support_free(data)

