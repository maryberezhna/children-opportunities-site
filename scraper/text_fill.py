# Всеукраїнська подія згадує місто фіналу, а брати участь можна звідусіль.
_NATIONAL = re.compile(r"всеукраїнськ|по всій україні|з усієї україни|вся україна", re.I)


def ua_cities_in(text: str) -> list[str]:
    return [c for c, rx in _CITY_RE.items() if rx.search(text or "")]


def city_from_text(text: str) -> str | None:
    """Рівно одне місто — інакше це перелік, а не місце проведення."""
    if _NATIONAL.search(text or ""):
        return None
    found = ua_cities_in(text)
    return found[0] if len(found) == 1 else None


