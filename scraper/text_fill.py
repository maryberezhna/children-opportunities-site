"""Дозаповнення з тексту: те, що прямо написано в назві чи описі, — факт.

Навіщо. Модель, що читає сторінку, інколи лишає поле порожнім, хоча відповідь
стоїть у самій назві: «ТВОЯ ШКОЛА — українська онлайн-школа» без формату,
«Музична школа №5 (Кривий Ріг)» без міста. Такий запис іде в чергу з «бракує:
…» і чекає, поки людина допише очевидне (Марія, 21.09.2026: «так має бути
щодо вартості, міста і всього, що можна заповнити»).

Правила — лише для порожнього поля: відповідь моделі завжди має пріоритет.
Кожне лишає модератору позначку, звідки взялось значення.

Кожне правило поміряне на записах, де модель поле вже заповнила (там є
правильна відповідь), 21.09.2026 по ~1450 записах бази:

    безкоштовно             302 із 302
    платно (ціна за період)   7 із 7
    місто                   334 із 336  (обидва промахи — не помилки правила)
    країна                   25 із 26   (після звуження до «в/у/до <країна>»)
    вік                     ~95% точно, ~98% у межах року
    тип за назвою           90–100% для слів нижче

Чого тут свідомо НЕМАЄ:
    • дат — «до 15 жовтня» в описі часто торішнє (пастка з дедлайнами з
      опису); дати з цитатою ставить планова перевірка (lifecycle.py);
    • типів «допомога», «волонтерство», «літня школа», «майстер-клас» — за
      назвою вони влучають лише в 40–75%;
    • країн за прикметником: «італійською мовою» — це мова, а не країна.
      Саме на цьому колись провалилась регулярка в backfill_geo.py (10–15%
      хибних: «англі» ловило «англійську мову»).

Модуль чистий: без бази й мережі, повністю під тестами.
"""
from __future__ import annotations

import re

from timing import has_repeat_signal

# ── Вартість ──────────────────────────────────────────────────────────────
_FREE = re.compile(r"безкоштовн|безоплатн|free of charge|без оплати", re.I)
# Безкоштовне лише частково — тестовий період, частина курсів, окремі
# категорії дітей. За правилом «родина платить хоч щось → платно» це не free.
_NOT_REALLY_FREE = re.compile(
    r"перш\w* (?:урок|занятт|місяц|тижд)|пробн\w*|тестов\w* період"
    r"|для пільгов|для впо|пільгов\w+ категор|знижк|частков"
    r"|частин\w* (?:курс|матеріал|функц|контент|місц)"
    r"|безкоштовн\w* (?:верс|тариф|план|частин|доступ|місц|модул|ресурс|реєстрац)"
    r"|модул\w* безкоштовн|етап\w* \d.{0,6}безкоштовн|freemium"
    r"|окрем\w+ (?:категор|учасник|дітей|конкурс)|деяк\w+|преміум|підписк|платн|опціональн"
    r"|\d[\d ]*\s*(?:грн|₴|€|євро|\$|доларів|usd|eur|zł|злот)",
    re.I)
_PAID = re.compile(
    r"(?:вартість|ціна|коштує|оплата|внесок|абонемент)\W{0,25}\d"
    r"|\d[\d ]*\s*(?:грн|₴|€|євро|\$|доларів|zł|злотих)\s*(?:/|на|за)\s*"
    r"(?:місяць|міс|заняття|урок|зміну|тиждень|день|рік|семестр|курс)",
    re.I)
# Гроші в тексті, які платить НЕ родина: приз, стипендія, виплата.
_MONEY_NOT_A_FEE = re.compile(
    r"безкоштовн|безоплатн|призов|премі|виграш|нагород|стипенді|грант|виплат|допомог|компенс|відшкод",
    re.I)


def cost_from_text(text: str) -> str | None:
    t = text or ""
    if _FREE.search(t) and not _NOT_REALLY_FREE.search(t):
        return "free"
    if _PAID.search(t) and not _MONEY_NOT_A_FEE.search(t):
        return "paid_affordable"
    return None


