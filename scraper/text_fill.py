# Києві з гостями з іншої країни.
_STAYS_IN_UA = re.compile(r"(?:в|у|В|У) Україні|(?i:консультац|поради|порад\b)")


def country_from_text(text: str) -> str | None:
    t = text or ""
    if _STAYS_IN_UA.search(t) or ua_cities_in(t):
        return None
    found = [code for code, rx in _COUNTRY_RE.items() if rx.search(t)]
    return found[0] if len(found) == 1 else None


# ── Вік ───────────────────────────────────────────────────────────────────
_RANGE = r"(\d{1,2})\s*[–—-]\s*(\d{1,2})"
# «6–9, 10–12, 13–15 років»: вікові групи стоять перед словом «років» у тому
# самому реченні — беремо всі й від найменшого до найбільшого.
_AGE_RANGES = re.compile(rf"{_RANGE}(?=[^.;:\n]{{0,45}}?(?:років|рок|р\.))")
_GRADES = re.compile(rf"{_RANGE}[- ]?(?:х|ти|і)?\s*клас")
_FROM_AGE = re.compile(r"(?:від|з)\s+(\d{1,2})\s+(?:років|рок)")
# Тривалість, а не вік: «термін навчання 6–8 років», «протягом 5 років».
_DURATION = re.compile(r"(?:термін|навчання|протягом|триває|тривалість|розпочинати|для початку)(?:\s+з)?\W{0,12}$",
                       re.I)


def _is_duration(text: str, start: int) -> bool:
    return bool(_DURATION.search(text[max(0, start - 30):start]))


def age_from_text(text: str) -> tuple[int, int] | None:
    t = text or ""
    lows, highs = [], []
    for m in _AGE_RANGES.finditer(t):
        if _is_duration(t, m.start()):
            continue
        a, b = int(m.group(1)), int(m.group(2))
        if a <= b <= 30:
            lows.append(a)
            highs.append(b)
    if lows:
        return max(0, min(lows)), min(18, max(highs))
    for m in _GRADES.finditer(t):
        a, b = int(m.group(1)), int(m.group(2))
        if 1 <= a <= b <= 11:
            # 5 клас → 10 років, 11 клас → 17: найширший чесний діапазон.
            lows.append(a + 5)
            highs.append(b + 6)
    if lows:
        return min(lows), min(18, max(highs))
    m = _FROM_AGE.search(t)
    if m and not _is_duration(t, m.start()) and int(m.group(1)) <= 18:
        return int(m.group(1)), 18
    return None


# ── Тип за назвою ─────────────────────────────────────────────────────────
# Лише слова, що влучають у 90–100% випадків. Порядок важливий: «олімпіада»
# раніше за «конкурс» (у назвах трапляється «конкурс-олімпіада»).
TYPE_BY_TITLE = (
    (re.compile(r"олімпіад", re.I), "olympiad"),
    (re.compile(r"хакатон", re.I), "hackathon"),
    (re.compile(r"стипенді", re.I), "scholarship"),
    (re.compile(r"грант", re.I), "grant"),
    (re.compile(r"обмін", re.I), "exchange"),
    (re.compile(r"фестивал", re.I), "festival"),
    (re.compile(r"конкурс|змаганн|чемпіонат|турнір", re.I), "competition"),
    (re.compile(r"гурт(?:ок|ки|ка)|секці", re.I), "club"),
)


def type_from_title(title: str) -> str | None:
    for rx, typ in TYPE_BY_TITLE:
        if rx.search(title or ""):
            return typ
    return None


# ── Періодичність ─────────────────────────────────────────────────────────
def recurrence_from_text(text: str) -> str | None:
    """«Щороку», «щорічний», «VII Всеукраїнський» — ті самі ознаки, за якими
    strip_invented_repeat (PR #372) ЗНІМАЄ вигадане «щороку». Тут навпаки:
    ставимо, коли ознака є, а дати немає."""
    return "annual" if has_repeat_signal(text or "") else None
