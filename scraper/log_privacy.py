"""Що можна писати в журнал GitHub Actions.

Репозиторій публічний, а з ним — і журнали кожного запуску воркфлоу: їх
може відкрити будь-хто. 07.10.2026 там знайшлися повні email отримувачів
листів олімпіади (поки — лише Марії), а після старту продажу там були б
адреси батьків, у пробному прогоні — ще й імена дітей. Тому в журнал —
лише замасковані адреси й початок id запису: досить, щоб знайти рядок у
базі, і нічого не каже сторонньому.
"""


def mask_email(value) -> str:
    """mama.petrenko@gmail.com → ma***@gmail.com."""
    s = str(value or "").strip()
    if "@" not in s:
        return "—"
    local, domain = s.rsplit("@", 1)
    return f"{local[:2]}***@{domain}"


def mask_chat(value) -> str:
    """7668754145 → …145. chat_id Telegram — ідентифікатор живої людини, а
    журнали Actions публічні; трьох останніх цифр досить, щоб разом із часом
    запуску знайти рядок у базі."""
    s = str(value or "").strip()
    return f"…{s[-3:]}" if s else "—"


def short_id(value) -> str:
    """Початок id запису (uuid) — щоб знайти рядок у базі."""
    return str(value or "")[:8] or "—"
